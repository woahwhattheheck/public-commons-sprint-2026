#!/usr/bin/env node
// MIT. Full workbook exchange through the original running Research application.
import {parseArgs} from 'node:util';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {ResearchWorkspaceClient} from '../workspace-client.mjs';
import {readResearchHostFile} from '../workspace-files.mjs';
import {need,parseJson,safeCode} from '../../node/store.mjs';

const commands={
 'template-view':['id','revision','section','template','offset','limit'],
 'template-record':['id','revision','kind','record'],
 'template-publication':['id','revision','publication','offset','limit'],
 'template-operation':['id','revision','request'],
 'template-stage-template':['id','input','source-file','sha256'],
 'template-stage-mapping':['id','input'],
 'template-stage-release':['id','input'],
 'template-stage-return':['id','input','source-file','sha256'],
 'template-stage-return-review':['id','input'],
 'template-review':['id','input'],
 'template-prepare-extraction-draft':['id','input'],
 'template-accept-extraction-draft':['id','input'],
 'template-download':['id','revision','blob','filename','out'],
};
const mutations={
 'template-stage-template':'stageTemplate','template-stage-mapping':'stageMapping',
 'template-stage-release':'stageRelease','template-stage-return':'stageReturn',
 'template-stage-return-review':'stageReturnReview','template-review':'review',
 'template-prepare-extraction-draft':'prepareExtractionDraft','template-accept-extraction-draft':'acceptExtractionDraft',
};
export const TEMPLATE_EXCHANGE_COMMANDS=Object.freeze(['template-help',...Object.keys(commands)]);
const usage=String.raw`Workbook exchange in the original Research workspace

  research-client template-COMMAND --connection-file /private/research.json --directory /original/dossier-store [OPTIONS]

Read the complete original history and immutable publication:
  template-view --id DOSSIER [--revision N --section overview|templates|template-editions|mappings|releases|returns|return-reviews|drafts|operations --template ID --offset N --limit N]
  template-record --id DOSSIER --kind edition|mapping|release|return|review|draft --record ID [--revision N]
  template-publication --id DOSSIER --publication ID [--revision N --offset N --limit N]
  template-operation --id DOSSIER --request ORIGINAL_REQUEST_ID [--revision N]

Use the first page's revision on every later page. A record contains its complete
retained inspection, mapping or return comparison. Its original blobs are available
with template-download; output is never shortened to the browser preview.

Inspect a full original client workbook:
  template-stage-template --id DOSSIER --input WORKBOOK_OPTIONS.json --source-file ORIGINAL.xlsx --sha256 SHA256
  template-stage-return --id DOSSIER --input RETURN_OPTIONS.json --source-file CLIENT_RETURN.xlsx --sha256 SHA256

WORKBOOK_OPTIONS.json contains filename and optional format/delimiter.
RETURN_OPTIONS.json also contains the original revision and releaseId.
The original file is read completely and matched to its expected SHA256 before
the same application's native workbook inspector is called. Maximum input:32 MiB.
Do not put body, bodyBase64 or bodyPath in these options.

Prepare a reviewable original action:
  template-stage-mapping --id DOSSIER --input MAPPING.json
  template-stage-release --id DOSSIER --input RELEASE.json
  template-stage-return-review --id DOSSIER --input RETURN_DECISIONS.json

These commands return the original action/data/expectedRevision and complete preview.
Retain the returned JSON. Author a complete reviewed request containing
{requestId,expectedRevision,actor:{id,name},action,data:{...prepared.data,reason}}.
No request ID, source assignment or review decision is generated by this command.

Commit that exact saved review:
  template-review --id DOSSIER --input ORIGINAL_REVIEW_REQUEST.json

Continue through the original assigned extraction reviewer:
  template-prepare-extraction-draft --id DOSSIER --input PREPARE_ORIGINAL_DRAFT.json
  template-accept-extraction-draft --id DOSSIER --input ACCEPT_ORIGINAL_DRAFT.json

PREPARE_ORIGINAL_DRAFT.json carries revision, reviewId, actor, requestId, resultSetId
and reason. The response includes the whole extraction request and its exact blob.
ACCEPT_ORIGINAL_DRAFT.json carries that reviewId, unchanged request, requestBlob,
receiptRequestId and reason. Keep the same original request and receipt IDs when
recovering a lost reply. Submission, independent review and resolution remain the
existing extraction commands.

Download any complete original workbook or retained JSON blob:
  template-download --id DOSSIER --blob SHA256 --out NEW_FILE [--revision N --filename "Client results.xlsx"]

The original Research file writer receives the full body, preserves an existing
destination, checks the selected blob hash and returns its actual bytes/SHA256.
The original filename may contain spaces and Unicode. An explicit filename selects
the workbook download name; omit it when downloading a non-workbook inspection blob.

Use the existing export/reopen commands for complete editable dossier JSON/gzip,
including every template edition, release, client return, original extraction request
and historical blob. Close detaches this client and leaves the application running.
`;

export async function main(argv=process.argv.slice(2),{output=process.stdout}={}){
 const [command,...args]=argv;
 if(!command||command==='template-help'||['help','--help','-h'].includes(command)){output.write(usage);return;}
 need(Object.hasOwn(commands,command),'COMMAND_UNKNOWN');
 const names=['connection-file','directory','timeout-ms',...commands[command]];
 const {values,tokens}=parseArgs({args,options:Object.fromEntries(names.map(name=>[name,{type:'string'}])),strict:true,tokens:true});
 const seen=new Set();
 for(const token of tokens)if(token.kind==='option'){need(!seen.has(token.name),'ARGUMENT_REPEATED');seen.add(token.name);}
 const required=name=>{need(typeof values[name]==='string'&&values[name].length>0,'ARGUMENT_REQUIRED');return values[name];};
 const number=name=>{
  if(values[name]===undefined)return undefined;
  need(/^(0|[1-9][0-9]{0,8})$/.test(values[name]),'INTEGER_ARGUMENT_REQUIRED');return Number(values[name]);
 };
 const hash=name=>{const value=required(name);need(/^[a-f0-9]{64}$/.test(value),'RESEARCH_SHA256_REQUIRED');return value;};
 const dossierId=required('id');
 const client=new ResearchWorkspaceClient({connectionFile:resolve(required('connection-file')),directory:resolve(required('directory'))},
  values['timeout-ms']===undefined?{}:{timeoutMs:number('timeout-ms')});
 const input=async()=>parseJson(await readResearchHostFile(resolve(required('input')),48*1024*1024));
 let result;
 try{
  const status=await client.status();need(status.api?.templateExchange===true,'TEMPLATE_HOST_BINDING_REQUIRED');
  const api=client.templateExchange(dossierId),revision=number('revision');
  if(command==='template-view')result=await api.page({revision,section:values.section,templateId:values.template,offset:number('offset'),limit:number('limit')});
  else if(command==='template-record')result=await api.record({revision,kind:required('kind'),recordId:required('record')});
  else if(command==='template-publication')result=await api.publication({revision,publicationId:required('publication'),offset:number('offset'),limit:number('limit')});
  else if(command==='template-operation')result=await api.operation({revision,requestId:required('request')});
  else if(command==='template-download')result=await api.download(hash('blob'),resolve(required('out')),{revision,filename:values.filename});
  else{
   let request=await input();need(request&&typeof request==='object'&&!Array.isArray(request),'JSON_OBJECT_REQUIRED');
   if(command==='template-stage-template'||command==='template-stage-return'){
    need(!['body','bodyBase64','bodyPath'].some(name=>Object.hasOwn(request,name)),'TEMPLATE_FILE_OPTIONS_INVALID');
    const body=await readResearchHostFile(resolve(required('source-file')),32*1024*1024,{sha256:hash('sha256')});
    request={...request,bodyBase64:Buffer.from(body).toString('base64')};
   }
   result=await api[mutations[command]](request);
  }
  output.write(JSON.stringify(result)+'\n');return result;
 }finally{await client.close();}
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))
 main().catch(error=>{process.stderr.write(JSON.stringify({error:safeCode(error.code,'TEMPLATE_COMMAND_FAILED'),
  outcomeUnknown:error.outcomeUnknown??false,recovery:error.recovery??null})+'\n');process.exitCode=1;});
