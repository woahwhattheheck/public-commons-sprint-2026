import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createOpenSearchWorkspace } from '../workspace/service.mjs';
import { startOpenSearchSeller } from '../start.mjs';
const root=resolve(process.env.OPENSEARCH_RECEIVING_DIRECTORY ?? process.argv[2] ?? 'opensearch-native-receiving');
await mkdir(root,{recursive:true,mode:0o700});
const nativeRoot=resolve(process.env.OPENSEARCH_NATIVE_METADATA ?? root);
const reportPath=root+'/native-merchant-journey.json', directory=root+'/workspace';
const env={...process.env,OPENSEARCH_PLAYGROUND_ENDPOINT:process.env.OPENSEARCH_PLAYGROUND_ENDPOINT};
const sourceFile=fileURLToPath(new URL('./playground-source.json',import.meta.url)), input={country:'US',minimum_price:0};
const source=JSON.parse(await readFile(sourceFile,'utf8'));
const prior={schema:'stellar-forge.opensearch-merchant-plan.v1',publicOrigin:'https://search.example.com',payment:{scheme:'exact',network:'stellar:testnet',amount:'10000',asset:'CABAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAFNSZ',payTo:'GAAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQDZ7H',maxTimeoutSeconds:60}};
const plan={...prior,routes:[{id:'flight_search',path:'/search/flights',method:'POST',query:'flights',serviceName:'Flight Search',description:'Search the public sample flight index in one consistent native snapshot.',parameterDescriptions:{country:'Two-letter departure country.',minimum_price:'Minimum average ticket price.'},example:input}]};
const planFile=root+'/flight-merchant-plan.json';
await writeFile(planFile,JSON.stringify(plan,null,2)+'\n',{mode:0o600});
const report={schema:'stellar-forge.opensearch-native-journey.v1',operation:'ASTRA-EE290-OPENSEARCH-20261011',startedAt:new Date().toISOString(),runtime:process.version,engine:JSON.parse(await readFile((process.env.OPENSEARCH_NATIVE_METADATA ?? nativeRoot)+'/native-engine.json','utf8')),stages:[]};
report.code=await Promise.all(['source.mjs','wire.mjs','declaration.mjs','projection.mjs','prepare.mjs','start.mjs','workspace/service.mjs','workspace/store.mjs'].map(async path=>({path,sha256:createHash('sha256').update(await readFile(new URL('../'+path,import.meta.url))).digest('hex')})));
let workspace,seller;
const stage=(name,data={})=>{report.stages.push({name,...data});console.log(JSON.stringify({stage:name,...data}));};
try {
 workspace=await createOpenSearchWorkspace({sourceFile,planFile,directory,env});
 const saved=workspace.save({requestId:'ee290-native-flights-save-1',title:'Native OpenSearch public flights',queryName:'flights',query:source.queries.flights,input,plan});
 assert.equal(saved.state,'COMPLETE'); const draft=saved.result.draft;
 const selection={draftId:draft.id,expectedRevision:draft.revision};
 workspace.validate(draft.id,draft.revision);
 stage('draft',selection);
 const capture=await workspace.run('capture',{requestId:'ee290-native-flights-capture-3',...selection});
 if(capture.state!=='COMPLETE')throw Object.assign(new Error(JSON.stringify(capture.error)),{operation:capture});
 const editionId=capture.result.editionId,edition=workspace.edition(editionId);
 const result=edition.original.result;
 assert.equal(result.schema,'stellar-forge.opensearch-result.v1');
 assert.equal(result.hitCount,7);assert.equal(result.hits.length,7);assert.equal(result.pages,3);assert.equal(result.truncated,true);
 assert.equal(result.total.relation,'gte');assert.equal(result.snapshotReleased,true);assert.equal(result.source.serverVersion,report.engine.version.number);
 assert.equal(result.source.clusterFingerprint,createHash('sha256').update(report.engine.cluster_uuid).digest('hex'));
 assert.equal(new Set(result.hits.map(h=>JSON.stringify([h._index,h._id]))).size,7);
 for(const hit of result.hits){assert.equal(hit._source.OriginCountry,'US');assert.ok(hit._source.AvgTicketPrice>=0);assert.equal(hit.sort.length,4);}
 const json=workspace.downloadEdition(editionId,'result.json'),csv=workspace.downloadEdition(editionId,'results.csv');
 assert.deepEqual(JSON.parse(json.body),result);assert.ok(csv.body.includes('FlightNum'));
 const resultSha256=createHash('sha256').update(json.body).digest('hex');
 await writeFile(root+'/native-flights-result.json',json.body,{mode:0o600});
 await writeFile(root+'/native-flights-result.csv',csv.body,{mode:0o600});
 stage('native-capture',{editionId,hitCount:result.hitCount,pages:result.pages,total:result.total,truncated:result.truncated,snapshotReleased:result.snapshotReleased,source:result.source,resultSha256});
 const prepared=await workspace.run('prepare',{requestId:'ee290-native-flights-prepare-1',...selection});
 if(prepared.state!=='COMPLETE')throw Object.assign(new Error(JSON.stringify(prepared.error)),{operation:prepared});
 const packageId=prepared.result.packageId,pack=workspace.package(packageId);
 assert.equal(pack.files.length,11);
 const module=await import(pathToFileURL(pack.handoff.client+'/seller-client.mjs').href);
 const request=module.buildRequest('flight_search',{body:input},{intentId:'ee290-native-flights-customer-1',acceptIndex:0,maxAtomic:'10000'});
 assert.equal(request.method,'POST');assert.deepEqual(JSON.parse(request.body),input);
 assert.equal(request.expect.asset,plan.payment.asset);assert.equal(request.expect.payTo,plan.payment.payTo);
 stage('original-customer-export',{packageId,fileCount:pack.files.length,url:request.url,method:request.method});
 seller=await startOpenSearchSeller({directory:pack.directory,env,port:0,operationsPort:null});
 assert.equal(seller.mode,'CHALLENGE_ONLY');assert.equal(seller.source.inspect().source.clusterFingerprint,result.source.clusterFingerprint);
 const publicUrl=new URL(request.url);
 const response=await fetch(seller.url+publicUrl.pathname+publicUrl.search,{method:request.method,headers:request.headers,body:request.body,redirect:'error'});
 const responseBody=await response.text();
 assert.equal(response.status,402);
 const encoded=response.headers.get('payment-required');assert.ok(encoded);
 const challenge=JSON.parse(Buffer.from(encoded,'base64').toString('utf8'));
 assert.equal(challenge.resource.url,request.url);assert.equal(challenge.accepts[0].amount,'10000');assert.equal(challenge.accepts[0].asset,request.expect.asset);
 const openapi=await (await fetch(seller.url+'/_seller/openapi.json')).json();assert.ok(openapi.paths['/search/flights'].post);
 const invalid=await fetch(seller.url+'/search/flights',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({country:'USA',minimum_price:0})});
 assert.equal(invalid.status,422);await invalid.text();
 stage('original-seller-http',{mode:seller.mode,status:response.status,invalidInputStatus:invalid.status,advertisedUrl:challenge.resource.url,openapiOperation:openapi.paths['/search/flights'].post.operationId,sourceStatus:seller.source.status()});
 await seller.close();seller=null;
 await workspace.close();workspace=null;
 workspace=await createOpenSearchWorkspace({sourceFile,planFile,directory,env});
 assert.equal(workspace.operation('ee290-native-flights-capture-3').result.editionId,editionId);
 assert.equal(workspace.operation('ee290-native-flights-prepare-1').result.packageId,packageId);
 assert.equal(createHash('sha256').update(workspace.downloadEdition(editionId,'result.json').body).digest('hex'),resultSha256);
 const same=await workspace.run('capture',{requestId:'ee290-native-flights-capture-3',...selection});assert.equal(same.result.editionId,editionId);
 stage('workspace-reopen',{draftId:draft.id,editionId,packageId,identicalResult:true,reusedOriginalRequest:true});
 report.state='PASS';report.completedAt=new Date().toISOString();report.directory=directory;
} catch(error) {
 report.state='FAIL';report.error={name:error.name,code:error.code,message:error.message,stack:error.stack,operation:error.operation};report.completedAt=new Date().toISOString();process.exitCode=1;
 console.error(JSON.stringify({error:report.error}));
} finally {
 await seller?.close().catch(()=>{});await workspace?.close().catch(()=>{});
 await writeFile(reportPath,JSON.stringify(report,null,2)+'\n',{mode:0o600});
 console.log(JSON.stringify({state:report.state,reportPath}));
}
