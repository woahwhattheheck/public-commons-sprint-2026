export const REDIS_SETUP_SCHEMA = 'stellar-forge.redis-connection-setup.v1';
const plain = value => value && typeof value === 'object' && !Array.isArray(value);
const clone = value => structuredClone(value);
const stableValue = value => Array.isArray(value) ? value.map(stableValue) : plain(value)
  ? Object.fromEntries(Object.keys(value).sort().map(key => [key, stableValue(value[key])])) : value;
const stable = value => JSON.stringify(stableValue(value));
const hash = value => createHash('sha256').update(value).digest('hex');
const encode = value => JSON.stringify(value, null, 2) + '\n';
const issue = (code, message, status = 422) => Object.assign(new Error(message), {code, status});
function fields(value, names) {
  if (!plain(value) || Object.keys(value).some(name => !names.includes(name)))
    throw issue('REDIS_SETUP_FIELDS_INVALID', 'Use the supported setup fields.');
}
function certificate(value) {
  if (typeof value !== 'string' || !value.isWellFormed() || !value.length ||
      Buffer.byteLength(value) > 1048576 || value.includes('PRIVATE KEY'))
    throw issue('REDIS_SETUP_CERTIFICATE_INVALID', 'Choose a PEM certificate bundle within 1 MiB.');
  const blocks = value.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g) ?? [];
  if (!blocks.length || value.replace(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g, '').trim())
    throw issue('REDIS_SETUP_CERTIFICATE_INVALID', 'The certificate file must contain only PEM certificates.');
  try { for (const block of blocks) new X509Certificate(block); }
  catch { throw issue('REDIS_SETUP_CERTIFICATE_INVALID', 'The certificate bundle could not be read.'); }
  return Buffer.from(value);
}
async function put(path, value) {
  const file = await open(path, 'wx', 0o600);
  try { await file.writeFile(value); await file.sync(); } finally { await file.close(); }
}
export async function redisSetupTemplates() {
  const [source, plan] = await Promise.all(['example-source.json', 'example-merchant-plan.json']
    .map(name => readFile(new URL('../' + name, import.meta.url), 'utf8').then(JSON.parse)));
  return {label:'Redis merchant', source, plan, certificates:{}};
}
export function normalizeRedisSetup(input, environment = process.env) {
  fields(input, ['label','source','plan','certificates']);
  const label = input.label ?? 'Redis merchant';
  if (typeof label !== 'string' || !label.isWellFormed() || !label.trim() || label.length > 200 ||
      /[\x00-\x1f\x7f]/.test(label))
    throw issue('REDIS_SETUP_LABEL_INVALID', 'Give the workspace a name within 200 characters.');
  const source = clone(input.source), plan = clone(input.plan), certificates = {};
  validateRedisSourceConfig(source);
  if (source.bindings !== undefined)
    throw issue('REDIS_SETUP_BINDINGS_INVALID', 'Import the original source declarations; customer bindings are generated by the merchant plan.');
  if (Buffer.byteLength(encode(source)) > 262144 || Buffer.byteLength(encode(plan)) > 262144)
    throw issue('REDIS_SETUP_CONFIGURATION_TOO_LARGE', 'Keep each source and merchant plan within 256 KiB.');
  fields(input.certificates ?? {}, REDIS_CERTIFICATE_FILES.map(item => item.profile));
  for (const item of REDIS_CERTIFICATE_FILES) {
    const value = input.certificates?.[item.profile];
    if (source.connection[item.profile] !== undefined) {
      if (value === undefined)
        throw issue('REDIS_SETUP_CERTIFICATE_REQUIRED', 'Choose the certificate bundle for ' + item.profile + '.');
      certificates[item.profile] = certificate(value);
      source.connection[item.profile] = item.file;
    } else if (value !== undefined)
      throw issue('REDIS_SETUP_CERTIFICATE_UNUSED', 'Enable the certificate on its connection or remove the unused file.');
  }
  const compiled = compileRedisMerchantPlan(source.queries, plan);
  const certificateDigests = Object.fromEntries(Object.entries(certificates).map(([name, value]) => [name, hash(value)]));
  const digest = hash(stable({label, source, plan, certificates:certificateDigests}));
  const environmentNames = requiredRedisEnvironment(source.connection).sort();
  const refs = environmentNames.map(name => {
    const value = environment[name], token = source.connection.transport === 'upstash-rest';
    const available = typeof value === 'string' && value.length > 0 && value.length <= 16384 &&
      !value.includes('\0') && (!token || !/[^\x21-\x7e]/.test(value));
    return {name, available};
  });
  return {label, source, plan, certificates, digest,
    review:{schema:REDIS_SETUP_SCHEMA, digest, label, connection:clone(source.connection),
      environment:refs, certificates:certificateDigests,
      queries:describeRedisQueries(compileRedisQueries(source.queries)),
      publicOrigin:plan.publicOrigin,
      routes:compiled.service.routes.map(route => ({id:route.id,url:route.offer.resource.url,payment:route.offer.accepts}))}};
}
export async function createRedisConnectionSetup({directory, initial, environment = process.env} = {}) {
  if (typeof directory !== 'string' || !directory)
    throw issue('REDIS_SETUP_DIRECTORY_REQUIRED', 'Choose the new workspace directory when starting setup.');
  const selected = resolve(directory), parent = await realpath(dirname(selected));
  const name = basename(selected);
  if (name === '.' || name === '..' || !name)
    throw issue('REDIS_SETUP_DIRECTORY_INVALID', 'Choose a new workspace directory.');
  const target = join(parent, name), parentStat = await lstat(parent);
  if (!parentStat.isDirectory()) throw issue('REDIS_SETUP_DIRECTORY_INVALID', 'The workspace parent must be an existing directory.');
  const existing = await lstat(target).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (existing) throw issue('REDIS_SETUP_DIRECTORY_EXISTS', 'Open the existing workspace, or choose a new directory for connection setup.', 409);
  const defaults = initial ? clone(initial) : await redisSetupTemplates();
  return new RedisConnectionSetup({directory:target, parent, initial:defaults, environment:{...environment}});
}
export class RedisConnectionSetup {
  constructor({directory,parent,initial,environment}) {
    this.directory=directory; this.parent=parent; this.initial=initial; this.environment=environment;
    this.id='redis-setup-'+randomUUID(); this.queue=Promise.resolve(); this.active=new Set();
    this.workspace=null; this.created=null; this.reviewed=null; this.closing=null; this.closed=false;
  }
  state() {
    return {schema:REDIS_SETUP_SCHEMA, setupId:this.id, directory:this.directory,
      status:this.created?'CREATED':'CONFIGURING', initial:clone(this.initial),
      created:this.created?clone(this.created):null};
  }
  writable() {
    if (this.closing || this.closed) throw issue('REDIS_SETUP_CLOSING', 'Connection setup is closing.', 409);
  }
  review(input) {
    this.writable();
    const result=normalizeRedisSetup(input,this.environment);
    this.reviewed=result.digest;
    return result.review;
  }
  serialize(action) {
    this.writable();
    const task=this.queue.catch(()=>{}).then(()=>{this.writable();return action();});
    this.queue=task; return task;
  }
  async materialize(input, callback) {
    const temp=await mkdtemp(join(this.parent,'.redis-setup-'));
    try {
      await put(join(temp,'source.json'),encode(input.source));
      await put(join(temp,'merchant-plan.json'),encode(input.plan));
      for (const item of REDIS_CERTIFICATE_FILES)
        if (input.certificates[item.profile]) await put(join(temp,item.file),input.certificates[item.profile]);
      return await callback(temp);
    } finally { await rm(temp,{recursive:true,force:true}); }
  }
  preview(input) {
    fields(input,['draft','digest','query','input']);
    const captured=clone(input);
    return this.serialize(async()=>{
      const draft=normalizeRedisSetup(captured.draft,this.environment);
      if (captured.digest!==draft.digest || this.reviewed!==draft.digest)
        throw issue('REDIS_SETUP_REVIEW_REQUIRED','Review this connection and its products before reading from the source.',409);
      if (typeof captured.query!=='string' || !Object.hasOwn(draft.source.queries,captured.query) || !plain(captured.input))
        throw issue('REDIS_SETUP_PREVIEW_INVALID','Choose a declared product and its input object.');
      if (draft.review.environment.some(ref=>!ref.available))
        throw issue('REDIS_SETUP_ENVIRONMENT_REQUIRED','Set these variables in the setup process environment: '+
          draft.review.environment.filter(ref=>!ref.available).map(ref=>ref.name).join(', ')+'.');
      return this.materialize(draft,async root=>{
        const controller=new AbortController(); this.active.add(controller); let source;
        try {
          ({source}=await openRedisSourceFile(join(root,'source.json'),{environment:this.environment}));
          if (this.closing) controller.abort();
          const data=await source.query(captured.query,captured.input,{signal:controller.signal});
          return {digest:draft.digest,query:captured.query,input:captured.input,observedAt:new Date().toISOString(),data};
        } catch(error) {
          if (typeof error?.code==='string' && /^REDIS_/.test(error.code)) throw error;
          throw issue('REDIS_SETUP_PREVIEW_FAILED','The source could not complete this read. Check its host, credentials, certificates and product input.');
        } finally {
          try { await source?.close(); } finally { this.active.delete(controller); }
        }
      });
    });
  }
  create(input) {
    fields(input,['draft','digest','requestId']);
    const captured=clone(input);
    if (typeof captured.requestId!=='string'||!/^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$/.test(captured.requestId))
      throw issue('REDIS_SETUP_REQUEST_INVALID','Use the original workspace creation request.');
    return this.serialize(async()=>{
      const draft=normalizeRedisSetup(captured.draft,this.environment);
      if (captured.digest!==draft.digest || this.reviewed!==draft.digest)
        throw issue('REDIS_SETUP_REVIEW_REQUIRED','Review the current connection, products and merchant terms before creating.',409);
      if (this.created) {
        if (this.created.requestId!==captured.requestId || this.created.digest!==draft.digest)
          throw issue('REDIS_SETUP_ALREADY_CREATED','This setup has already created its selected workspace.',409);
        return {...clone(this.created),recovered:true};
      }
      await this.materialize(draft,async root=>{
        const workspace=await createRedisAuthoringWorkspace({
          directory:this.directory,sourceFile:join(root,'source.json'),planFile:join(root,'merchant-plan.json'),
          label:draft.label,environment:this.environment});
        // The original workspace exists now. Retain it even if removing the input
        // directory fails, so the same request and GET state can recover it.
        this.workspace=workspace;
        this.created={requestId:captured.requestId,digest:draft.digest,directory:workspace.root,
          ...redisWorkspaceBinding(workspace.metadata()),createdAt:new Date().toISOString()};
      });
      return clone(this.created);
    });
  }
  close() {
    if (this.closing) return this.closing;
    this.closing=(async()=>{
      for (const controller of this.active) controller.abort();
      await this.queue.catch(()=>{});
      try { await this.workspace?.close(); } finally { this.closed=true; }
    })();
    return this.closing;
  }
}
