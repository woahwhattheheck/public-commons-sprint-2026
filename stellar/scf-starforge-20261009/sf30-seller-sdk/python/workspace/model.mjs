export const WORKSPACE_SCHEMA = 'stellar-forge.python-workspace.v1';
export const EXPORT_SCHEMA = 'stellar-forge.python-workspace-export.v1';
export const MAX_BUNDLE_BYTES = 256 * 1024 * 1024;
const MiB = 1024 * 1024, SOURCE_LIMIT = 32 * MiB, FILE_LIMIT = 8 * MiB;
const TABLES = new Set(['revisions', 'previews', 'stages', 'customers']);
const INFLIGHT = new Set(['QUEUED', 'RUNNING']);
const CACHE_DIRS = new Set(['.git', '.hg', '.svn', '.venv', 'venv', '__pycache__', '.pytest_cache', '.mypy_cache', '.ruff_cache', 'node_modules']);
const now = () => new Date().toISOString();
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const clone = value => JSON.parse(JSON.stringify(value));
const formatted = value => Buffer.from(JSON.stringify(value, null, 2) + '\n');
const own = (value, key) => Object.prototype.hasOwnProperty.call(value, key);
function normalized(value) {
  if (Array.isArray(value)) return value.map(normalized);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(key => [key, normalized(value[key])]));
  return value;
}
const stable = value => JSON.stringify(normalized(value));
function problem(code, message, status = 400) { return Object.assign(new Error(message), { code, status }); }
function object(value, label = 'Input') {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw problem('INVALID_INPUT', label + ' must be a JSON object.');
  return value;
}
function identifier(value, label = 'Identifier') {
  if (typeof value !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_-]{0,159}$/.test(value))
    throw problem('INVALID_ID', label + ' must use 1–160 letters, numbers, underscores or hyphens.');
  return value;
}
function releaseId(value) {
  if (typeof value !== 'string' || !/^[a-z0-9][a-z0-9_-]{0,63}$/.test(value))
    throw problem('INVALID_ID', 'Release and export names use 1–64 lowercase letters, numbers, underscores or hyphens.');
  return value;
}
function note(value, fallback = '') {
  value = value ?? fallback;
  if (typeof value !== 'string' || value.length > 2000 || value.includes('\0')) throw problem('INVALID_INPUT', 'A note must contain at most 2,000 characters.');
  return value;
}
function sourcePath(value) {
  if (typeof value !== 'string' || !value || value.length > 4096 || /[\\\u0000-\u001f\u007f]/.test(value) || value.startsWith('/') ||
      value.split('/').some(part => !part || part === '.' || part === '..')) throw problem('INVALID_PATH', 'Use a relative source path without empty, dot or parent segments.');
  return value;
}
function authoredPath(value) {
  sourcePath(value);
  if (value.split('/').some(part => CACHE_DIRS.has(part)) || /\.py[co]$/.test(value))
    throw problem('EXCLUDED_SOURCE', 'The original Python release excludes dependency, cache and generated bytecode paths: ' + value);
  return value;
}
function digest(value) {
  if (typeof value !== 'string' || !/^[0-9a-f]{64}$/.test(value)) throw problem('INVALID_DIGEST', 'Expected a SHA-256 digest.');
  return value;
}
function utf8(bytes) {
  // Preserve every original text byte, including an optional UTF-8 BOM.
  try { return new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes); } catch { return null; }
}
function describe(path, bytes) {
  const text = utf8(bytes);
  return { path, bytes: bytes.length, sha256: hash(bytes), editable: bytes.length <= 2 * MiB && text !== null && !text.includes('\0') };
}
function errorRecord(error) { return { code: error.code ?? 'WORKSPACE_ERROR', message: error.message ?? String(error) }; }
function processAlive(pid) {
  if (!Number.isSafeInteger(pid) || pid < 1) return false;
  try { process.kill(pid, 0); return true; } catch (error) { return error.code === 'EPERM'; }
}
function isInside(root, target) {
  const path = relative(root, target);
  return path === '' || !isAbsolute(path) && path !== '..' && !path.startsWith('..' + sep);
}
async function regular(path, maximum = FILE_LIMIT) {
  const stat = await lstat(path);
  if (!stat.isFile() || stat.size > maximum) throw problem('INVALID_FILE', 'Expected a regular file up to ' + maximum + ' bytes: ' + path);
  const bytes = await readFile(path);
  if (bytes.length > maximum) throw problem('FILE_LIMIT', 'File grew beyond its retained limit: ' + path);
  return bytes;
}
async function directory(path) {
  if (!(await lstat(path)).isDirectory()) throw problem('INVALID_DIRECTORY', 'Expected a real directory: ' + path);
}
async function syncDirectory(path) {
  let handle;
  try { handle = await open(path, 'r'); await handle.sync(); }
  catch (error) { if (!['EINVAL', 'EPERM', 'EISDIR', 'ENOTSUP'].includes(error.code)) throw error; }
  finally { await handle?.close(); }
}
async function writeNew(path, bytes) {
  const handle = await open(path, 'wx', 0o600);
  try { await handle.writeFile(bytes); await handle.sync(); } finally { await handle.close(); }
}
async function privateParents(root, path) {
  let current = root;
  for (const part of sourcePath(path).split('/').slice(0, -1)) {
    current = join(current, part);
    try { await mkdir(current, { mode: 0o700 }); }
    catch (error) { if (error.code !== 'EEXIST') throw error; await directory(current); }
  }
}
async function atomic(path, bytes) {
  const temp = path + '.' + randomUUID() + '.tmp';
  try { await writeNew(temp, bytes); await rename(temp, path); await syncDirectory(dirname(path)); }
  finally { await rm(temp, { force: true }); }
}
function makeDatabase(path) {
  const db = new DatabaseSync(path);
  db.exec('PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL; PRAGMA busy_timeout=3000;');
  db.exec('CREATE TABLE IF NOT EXISTS metadata (id INTEGER PRIMARY KEY CHECK (id = 1), value TEXT NOT NULL);' +
    [...TABLES].map(table => 'CREATE TABLE IF NOT EXISTS ' + table + ' (id TEXT PRIMARY KEY, value TEXT NOT NULL);').join(''));
  return db;
}
function previewSummary(job) {
  const { id, operationId, revisionId, function: name, status, createdAt, startedAt = null, endedAt = null, result = null, error = null } = job;
  return { id, operationId, revisionId, function: name, status, createdAt, startedAt, endedAt, result, error,
    ...(job.cancelRequestedAt ? { cancelRequestedAt: job.cancelRequestedAt } : {}) };
}
function revisionSummary(revision) {
  return { id: revision.id, parent: revision.parent, createdAt: revision.createdAt, note: revision.note,
    entry: revision.entry, files: revision.files.length, bytes: revision.files.reduce((sum, file) => sum + file.bytes, 0), digest: revision.digest };
}

/** Create-only capture from an operator-selected original declaration and helper root. No Python executes. */
export async function createWorkspace(root, { config, pythonRoot, label } = {}) {
  if (typeof config !== 'string' || !config) throw problem('CONFIG_REQUIRED', 'Select an existing Python merchant declaration with --config.');
  root = resolve(root); config = resolve(config);
  const selectedRoot = pythonRoot === undefined ? undefined : resolve(pythonRoot);
  const prepared = await preparePythonRelease(config, { sourceRoot: selectedRoot });
  if (selectedRoot !== undefined) {
    const canonicalTarget = join(await realpath(dirname(root)), root.split(sep).at(-1));
    if (isInside(await realpath(selectedRoot), canonicalTarget)) throw problem('WORKSPACE_LOCATION', 'Create the workspace outside the selected Python helper directory.');
  }
  await mkdir(root, { mode: 0o700 });
  let workspace;
  try {
    await mkdir(join(root, 'blobs'), { mode: 0o700 });
    await mkdir(join(root, 'operations'), { mode: 0o700 });
    await mkdir(join(root, 'customer-exports'), { mode: 0o700 });
    await writeNew(join(root, 'workspace.sqlite3'), Buffer.alloc(0));
    await initReleaseStore(join(root, 'release-store'));
    const db = makeDatabase(join(root, 'workspace.sqlite3'));
    workspace = new PythonWorkspace(root, db);
    const meta = { schema: WORKSPACE_SCHEMA, id: 'ws-' + randomUUID(), label: note(label, prepared.declaration.serviceName ?? 'Python merchant'),
      createdAt: now(), head: null, origin: { config, pythonRoot: selectedRoot ?? null, workingDirectory: process.cwd(),
        declarationSourcePath: prepared.python.declarationSourceFile?.slice('python/source/'.length) ?? null,
        refreshAvailable: true } };
    db.prepare('INSERT INTO metadata(id,value) VALUES(1,?)').run(JSON.stringify(meta));
    await workspace.capturePrepared(prepared, { expectedHead: null, note: 'Imported selected application source' });
    await syncDirectory(root);
    return workspace;
  } catch (error) {
    await workspace?.close().catch(() => {}); await rm(root, { recursive: true, force: true }); throw error;
  }
}

export async function openWorkspace(root) {
  root = resolve(root); await directory(root); await directory(join(root, 'blobs'));
  if (!(await lstat(join(root, 'workspace.sqlite3'))).isFile()) throw problem('INVALID_WORKSPACE', 'Expected the original regular workspace database.');
  const db = makeDatabase(join(root, 'workspace.sqlite3'));
  const workspace = new PythonWorkspace(root, db);
  try {
    if (workspace.metadata().schema !== WORKSPACE_SCHEMA) throw problem('INVALID_WORKSPACE', 'Unsupported Python workspace schema.');
    await readReleaseState(workspace.releaseRoot);
    workspace.recoverPreviews();
    await workspace.reconcileStages();
    return workspace;
  } catch (error) { db.close(); throw error; }
}

export class PythonWorkspace {
  constructor(root, db) {
    this.root = root; this.releaseRoot = join(root, 'release-store'); this.db = db;
    this.owner = { pid: process.pid, host: hostname(), token: randomUUID() };
    this.jobs = new Map(); this.managed = null; this.lastError = null; this.closing = null; this.closed = false;
  }
  metadata() {
    const row = this.db.prepare('SELECT value FROM metadata WHERE id=1').get();
    if (!row) throw problem('INVALID_WORKSPACE', 'Workspace metadata is missing.');
    return JSON.parse(row.value);
  }
  rows(table) {
    if (!TABLES.has(table)) throw new TypeError('Unknown workspace table.');
    return this.db.prepare('SELECT value FROM ' + table + ' ORDER BY rowid DESC').all().map(row => JSON.parse(row.value));
  }
  row(table, id, required = true) {
    if (!TABLES.has(table)) throw new TypeError('Unknown workspace table.');
    identifier(id);
    const row = this.db.prepare('SELECT value FROM ' + table + ' WHERE id=?').get(id);
    if (!row && required) throw problem('NOT_FOUND', 'The saved ' + table + ' record does not exist: ' + id, 404);
    return row ? JSON.parse(row.value) : null;
  }
  put(table, value) {
    if (!TABLES.has(table)) throw new TypeError('Unknown workspace table.');
    this.db.prepare('INSERT INTO ' + table + '(id,value) VALUES(?,?) ON CONFLICT(id) DO UPDATE SET value=excluded.value').run(value.id, JSON.stringify(value));
  }
  transaction(action) {
    this.db.exec('BEGIN IMMEDIATE');
    try { const result = action(); this.db.exec('COMMIT'); return result; }
    catch (error) {
      // SQLite may already have rolled back after a storage failure.
      // Preserve the original failure so the operator can recover its cause.
      try { this.db.exec('ROLLBACK'); } catch {}
      throw error;
    }
  }
  writable() { if (this.closing || this.closed) throw problem('WORKSPACE_CLOSING', 'The workspace is shutting down.', 409); }
  async putBlob(bytes) {
    const sha256 = hash(bytes), path = join(this.root, 'blobs', sha256);
    try { await writeNew(path, bytes); await syncDirectory(dirname(path)); }
    catch (error) {
      if (error.code !== 'EEXIST') throw error;
      const previous = await regular(path, Math.max(bytes.length, FILE_LIMIT));
      if (!previous.equals(bytes)) throw problem('SOURCE_CHANGED', 'A retained content blob no longer matches its digest.');
    }
    return sha256;
  }
  async blob(sha256, maximum = MAX_BUNDLE_BYTES) {
    const bytes = await regular(join(this.root, 'blobs', digest(sha256)), maximum);
    if (hash(bytes) !== sha256) throw problem('SOURCE_CHANGED', 'Retained source or result bytes changed: ' + sha256);
    return bytes;
  }
  runnable(revision, sourceRoot, configPath) {
    let declaration;
    try { declaration = object(JSON.parse(revision.declarationText.replace(/^\uFEFF/, '')), 'Declaration'); }
    catch (error) { throw problem('INVALID_DECLARATION', 'Correct the saved merchant declaration JSON: ' + error.message); }
    // Validate the complete original declaration before rebinding only its selected local paths.
    compilePythonMerchant(declaration, { baseDir: dirname(configPath) });
    const effective = { ...declaration, application: relative(dirname(configPath), join(sourceRoot, revision.entry)).split(sep).join('/') };
    if (typeof declaration.python === 'string' && declaration.python.includes('/') && !isAbsolute(declaration.python))
      effective.python = resolve(this.metadata().origin.workingDirectory, declaration.python);
    return effective;
  }
  validation(revision) {
    try {
      const source = join(this.root, 'selected-source');
      const config = revision.declarationSourcePath ? join(source, revision.declarationSourcePath) : join(this.root, 'selected-declaration.json');
      const compiled = compilePythonMerchant(this.runnable(revision, source, config), { baseDir: dirname(config) });
      return { ok: true, error: null, options: compiled.options, functions: compiled.functions, routes: compiled.service.routes };
    } catch (error) { return { ok: false, error: errorRecord(error), options: null, functions: {}, routes: [] }; }
  }
  revision(id = this.metadata().head) {
    const revision = this.row('revisions', id);
    return { ...revision, validation: this.validation(revision) };
  }
  async file(revisionId, path) {
    sourcePath(path);
    const revision = this.row('revisions', revisionId), file = revision.files.find(item => item.path === path);
    if (!file) throw problem('NOT_FOUND', 'That file is not in this saved revision.', 404);
    const bytes = await this.blob(file.sha256, FILE_LIMIT), text = utf8(bytes);
    return { ...file, encoding: text === null ? 'base64' : 'utf8', text, base64: text === null ? bytes.toString('base64') : null };
  }
  async saveRecord(fields, expectedHead) {
    this.writable();
    const files = fields.files.sort((a, b) => a.path.localeCompare(b.path));
    const paths = new Set(); let total = 0;
    for (const file of files) {
      authoredPath(file.path); digest(file.sha256);
      if (paths.has(file.path) || !Number.isSafeInteger(file.bytes) || file.bytes < 0 || file.bytes > FILE_LIMIT) throw problem('INVALID_SOURCE', 'Source files need unique paths and fit the original 8 MiB file limit.');
      paths.add(file.path); total += file.bytes;
    }
    if (!files.length || files.length > 512 || total > SOURCE_LIMIT) throw problem('SOURCE_LIMIT', 'The original Python snapshot allows 512 files and 32 MiB of selected source.');
    authoredPath(fields.entry);
    const entry = files.find(file => file.path === fields.entry);
    if (!entry || !fields.entry.endsWith('.py') || entry.bytes > 2 * MiB) throw problem('INVALID_ENTRY', 'Select a retained .py entry file up to the original 2 MiB limit.');
    if (typeof fields.declarationText !== 'string' || Buffer.byteLength(fields.declarationText) > MiB) throw problem('DECLARATION_LIMIT', 'The merchant declaration must fit the original 1 MiB limit.');
    const revision = { ...fields, schema: 'stellar-forge.python-workspace-revision.v1', id: 'r-' + randomUUID(),
      parent: expectedHead, createdAt: now(), note: note(fields.note), files };
    revision.digest = hash(stable({ entry: revision.entry, declarationText: revision.declarationText,
      declarationSourcePath: revision.declarationSourcePath, sourceScope: revision.sourceScope, files }));
    this.transaction(() => {
      const metadata = this.metadata();
      if (metadata.head !== expectedHead) throw problem('WORKSPACE_CONFLICT', 'The saved source changed. Refresh the current revision before saving this draft.', 409);
      this.db.prepare('INSERT INTO revisions(id,value) VALUES(?,?)').run(revision.id, JSON.stringify(revision));
      this.db.prepare('UPDATE metadata SET value=? WHERE id=1').run(JSON.stringify({ ...metadata, head: revision.id, updatedAt: revision.createdAt }));
    });
    return this.revision(revision.id);
  }
  async capturePrepared(prepared, { expectedHead, note: changeNote }) {
    const files = [];
    for (const item of prepared.sourceFiles) {
      const path = item.file.slice('python/source/'.length); await this.putBlob(item.data); files.push(describe(path, item.data));
    }
    return this.saveRecord({ entry: prepared.python.entry.slice('python/source/'.length), declarationText: utf8(prepared.configBytes),
      declarationSourcePath: prepared.python.declarationSourceFile?.slice('python/source/'.length) ?? null,
      sourceScope: prepared.python.sourceScope, note: changeNote, files }, expectedHead);
  }
  async save(input) {
    this.writable(); object(input); const base = this.row('revisions', input.baseRevision);
    if (typeof input.expectedHead !== 'string') throw problem('EXPECTED_HEAD_REQUIRED', 'Supply the current saved revision as expectedHead.');
    const edits = input.files ?? [], remove = input.remove ?? [];
    if (!Array.isArray(edits) || !Array.isArray(remove) || edits.length + remove.length > 1024) throw problem('INVALID_SOURCE', 'Send changed files and removed paths as arrays.');
    const files = new Map(base.files.map(file => [file.path, file]));
    const changed = new Map(); const removals = new Set();
    for (const path of remove) { authoredPath(path); removals.add(path); files.delete(path); }
    for (const edit of edits) {
      object(edit, 'File edit'); authoredPath(edit.path);
      if (changed.has(edit.path) || removals.has(edit.path) || (typeof edit.text === 'string') === (typeof edit.base64 === 'string'))
        throw problem('INVALID_SOURCE', 'Each changed file needs one unique path and either text or base64; it cannot also be removed.');
      let bytes;
      if (typeof edit.text === 'string') bytes = Buffer.from(edit.text);
      else {
        if (edit.base64.length > Math.ceil(FILE_LIMIT / 3) * 4 || !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(edit.base64)) throw problem('INVALID_BASE64', 'File base64 must be canonical and fit the original file limit.');
        bytes = Buffer.from(edit.base64, 'base64');
      }
      if (bytes.length > FILE_LIMIT) throw problem('FILE_LIMIT', 'A source asset exceeds the original 8 MiB limit.');
      changed.set(edit.path, bytes); files.set(edit.path, describe(edit.path, bytes));
    }
    let declarationText = input.declarationText ?? base.declarationText;
    let declarationSourcePath = base.declarationSourcePath;
    if (declarationSourcePath && !files.has(declarationSourcePath)) declarationSourcePath = null;
    if (declarationSourcePath) {
      if (changed.has(declarationSourcePath)) {
        const editedDeclaration = utf8(changed.get(declarationSourcePath));
        if (editedDeclaration === null) throw problem('INVALID_DECLARATION', 'The declaration source file must be UTF-8 text.');
        if (declarationText !== base.declarationText && declarationText !== editedDeclaration) throw problem('DECLARATION_CONFLICT', 'The declaration editor and its source file contain different edits. Save one consistent declaration.', 409);
        declarationText = editedDeclaration;
      }
      if (declarationText !== base.declarationText) {
        const bytes = Buffer.from(declarationText); changed.set(declarationSourcePath, bytes); files.set(declarationSourcePath, describe(declarationSourcePath, bytes));
      }
    }
    for (const bytes of changed.values()) await this.putBlob(bytes);
    return this.saveRecord({ entry: input.entry ?? base.entry, declarationText, declarationSourcePath,
      sourceScope: base.sourceScope === 'SOURCE_DIRECTORY' || files.size > 1 ? 'SOURCE_DIRECTORY' : 'ENTRY_MODULE_ONLY',
      note: input.note, files: [...files.values()], basedOn: base.id }, input.expectedHead);
  }
  async restore(input) {
    object(input); const revision = this.row('revisions', input.revisionId);
    return this.saveRecord({ entry: revision.entry, declarationText: revision.declarationText, declarationSourcePath: revision.declarationSourcePath,
      sourceScope: revision.sourceScope, files: revision.files, restoredFrom: revision.id, note: input.note ?? 'Restored ' + revision.id }, input.expectedHead);
  }
  async refreshSource(input) {
    this.writable(); object(input); const origin = this.metadata().origin;
    if (origin.refreshAvailable !== true) throw problem('SOURCE_LOCATION_REQUIRED', 'This imported workspace retains its sources. To capture another host directory, create a workspace with its explicit --config and --python-root selections.', 409);
    const prepared = await preparePythonRelease(origin.config, { sourceRoot: origin.pythonRoot ?? undefined });
    return this.capturePrepared(prepared, { expectedHead: input.expectedHead, note: input.note ?? 'Refreshed original selected source' });
  }
  async materialize(revisionId) {
    const revision = this.row('revisions', revisionId), validation = this.validation(revision);
    if (!validation.ok) throw problem('INVALID_DECLARATION', validation.error.message);
    const directory = join(this.root, 'operations', 'source-' + randomUUID()); await mkdir(directory, { mode: 0o700 });
    const sourceRoot = join(directory, 'source');
    try {
      await mkdir(sourceRoot, { mode: 0o700 });
      for (const file of revision.files) { await privateParents(sourceRoot, file.path); await writeNew(join(sourceRoot, file.path), await this.blob(file.sha256, FILE_LIMIT)); }
      const config = revision.declarationSourcePath ? join(sourceRoot, revision.declarationSourcePath) : join(directory, 'merchant.json');
      const declaration = this.runnable(revision, sourceRoot, config), bytes = formatted(declaration);
      if (revision.declarationSourcePath) await atomic(config, bytes); else await writeNew(config, bytes);
      const compiled = compilePythonMerchant(declaration, { baseDir: dirname(config) });
      return { directory, sourceRoot, config, compiled, revision,
        pythonRoot: revision.sourceScope === 'SOURCE_DIRECTORY' ? sourceRoot : undefined,
        close: () => rm(directory, { recursive: true, force: true }) };
    } catch (error) { await rm(directory, { recursive: true, force: true }); throw error; }
  }
  recoverPreviews() {
    for (const job of this.rows('previews')) {
      if (INFLIGHT.has(job.status) && (!job.owner || job.owner.host === hostname() && !processAlive(job.owner.pid))) {
        this.put('previews', { ...job, status: 'INTERRUPTED', endedAt: now(), error: { code: 'PREVIEW_INTERRUPTED',
          message: 'The process that owned this private preview ended before recording a complete result. This operation is retained and was not executed again.' } });
      }
    }
  }
  async preview(input) {
    this.writable(); object(input); identifier(input.operationId, 'Preview operation ID');
    identifier(input.revisionId, 'Revision ID');
    if (typeof input.function !== 'string') throw problem('FUNCTION_REQUIRED', 'Select a saved public Python function.');
    object(input.input, 'Function input');
    const fingerprint = hash(stable({ revisionId: input.revisionId, function: input.function, input: input.input }));
    const id = 'p-' + hash(input.operationId);
    const existing = this.row('previews', id, false);
    if (existing) {
      if (existing.fingerprint !== fingerprint) throw problem('PREVIEW_CONFLICT', 'That preview operation ID already belongs to different source or input.', 409);
      return this.previewDetail(id);
    }
    const revision = this.revision(input.revisionId);
    if (!revision.validation.ok) throw problem('INVALID_DECLARATION', revision.validation.error.message);
    if (!own(revision.validation.functions, input.function)) throw problem('UNKNOWN_FUNCTION', 'This saved declaration has no selected function.');
    const definition = revision.validation.functions[input.function];
    if (Buffer.byteLength(JSON.stringify(input.input)) > definition.maxInputBytes) throw problem('INPUT_LIMIT', 'The private preview input exceeds this function’s original byte limit.');
    previewContext(definition, input.input);
    const job = { id, operationId: input.operationId, revisionId: input.revisionId, function: input.function,
      input: clone(input.input), fingerprint, status: 'QUEUED', createdAt: now(), startedAt: null, endedAt: null,
      result: null, error: null, pool: null, shutdown: null, owner: this.owner };
    const inserted = this.transaction(() => {
      const previous = this.row('previews', id, false);
      if (previous) {
        if (previous.fingerprint !== fingerprint) throw problem('PREVIEW_CONFLICT', 'That operation ID belongs to another request.', 409);
        return false;
      }
      this.db.prepare('INSERT INTO previews(id,value) VALUES(?,?)').run(id, JSON.stringify(job)); return true;
    });
    if (inserted) {
      const controller = new AbortController();
      const active = { controller, completion: null }; this.jobs.set(id, active);
      active.completion = Promise.resolve().then(() => this.executePreview(id, controller)).finally(() => this.jobs.delete(id));
      // A retained terminal row is the primary error channel; close still observes completion errors.
      active.completion.catch(error => { this.lastError = errorRecord(error); });
    }
    return this.previewDetail(id);
  }
  async executePreview(id, controller) {
    let job = this.row('previews', id), materialized, source, result = null, failure = null, shutdown = null, pool = null;
    job = { ...job, status: 'RUNNING', startedAt: now() }; this.put('previews', job);
    try {
      controller.signal.throwIfAborted(); materialized = await this.materialize(job.revisionId);
      controller.signal.throwIfAborted();
      const entry = materialized.revision.files.find(file => file.path === materialized.revision.entry);
      source = await createPythonSource(materialized.compiled, { expectedApplicationSha256: entry.sha256 });
      controller.signal.throwIfAborted();
      const definition = materialized.compiled.functions[job.function];
      const bytes = await source.call(job.function, previewContext(definition, job.input), { signal: controller.signal });
      const sha256 = await this.putBlob(bytes);
      result = { bytes: bytes.length, sha256, contentType: definition.output.contentType };
    } catch (error) { failure = errorRecord(error); }
    finally {
      if (source) {
        try { shutdown = await source.close(); pool = source.stats(); }
        catch (error) { failure ??= errorRecord(error); try { pool = source.stats(); } catch {} }
      }
      if (materialized) await materialized.close().catch(error => { failure ??= errorRecord(error); });
    }
    const latest = this.row('previews', id);
    const status = result && !failure ? 'COMPLETED' : controller.signal.aborted ? 'CANCELLED' : 'FAILED';
    this.put('previews', { ...latest, status, endedAt: now(), result, pool, shutdown,
      error: status === 'CANCELLED' ? { code: 'PREVIEW_CANCELLED', message: 'The private preview was cancelled; the owned Python source was closed.' } : failure });
  }
  async previewDetail(id) {
    const job = this.row('previews', id);
    let result = job.result;
    if (result) {
      const bytes = await this.blob(result.sha256), text = utf8(bytes);
      result = { ...result, text, base64: text === null ? bytes.toString('base64') : null };
    }
    return { ...previewSummary(job), input: job.input, result, pool: job.pool, shutdown: job.shutdown };
  }
  async previewOutput(id) {
    const job = this.row('previews', id);
    if (!job.result) throw problem('RESULT_UNAVAILABLE', 'This preview has no retained output bytes.', 409);
    return { bytes: await this.blob(job.result.sha256), contentType: job.result.contentType, sha256: job.result.sha256 };
  }
  async cancelPreview(input) {
    object(input); const job = this.row('previews', input.id);
    if (!INFLIGHT.has(job.status)) return this.previewDetail(job.id);
    const active = this.jobs.get(job.id);
    if (!active) throw problem('PREVIEW_NOT_OWNED', 'The current console does not own that preview process. Its original result remains in the workspace.', 409);
    this.put('previews', { ...job, cancelRequestedAt: now() }); active.controller.abort(new Error('Operator cancelled private preview.'));
    await active.completion; return this.previewDetail(job.id);
  }
  stageMatches(record, release) {
    return release.source?.kind === 'PYTHON_APPLICATION' && release.python?.configSha256 === record.expected.configSha256 &&
      release.python?.sourceSha256 === record.expected.sourceSha256 && release.python?.executionSha256 === record.expected.executionSha256 &&
      stable(release.runtime) === stable(record.runtime) && release.label === record.label;
  }
  async reconcileStages() {
    for (const row of this.rows('stages')) {
      if (row.status === 'STAGED') continue;
      try {
        const release = await inspectRelease(this.releaseRoot, row.releaseId);
        if (!this.stageMatches(row, release)) throw problem('STAGE_SOURCE_CHANGED', 'The native release ID contains different source or runtime terms.');
        this.put('stages', { ...row, status: 'STAGED', digest: release.digest, completedAt: now(), error: null, release });
      } catch (error) {
        if (error.code !== 'ENOENT') this.put('stages', { ...row, status: 'FAILED', error: errorRecord(error) });
        else if (row.status === 'STAGING' && (!row.owner || row.owner.host === hostname() && !processAlive(row.owner.pid)))
          this.put('stages', { ...row, status: 'INTERRUPTED', error: { code: 'STAGE_INTERRUPTED', message: 'Staging ended before the original immutable release was published. Retry the same saved stage request.' } });
      }
    }
  }
  async stage(input) {
    this.writable(); object(input); releaseId(input.id); const revision = this.row('revisions', input.revisionId);
    if (input.runtime !== undefined) object(input.runtime, 'Release runtime');
    const runtime = { port: input.runtime?.port ?? 8423 };
    if (input.runtime && own(input.runtime, 'facilitator')) runtime.facilitator = new URL(input.runtime.facilitator).href.replace(/\/$/, '');
    if (input.runtime && own(input.runtime, 'allowLocalFacilitator') && typeof input.runtime.allowLocalFacilitator !== 'boolean')
      throw problem('INVALID_RUNTIME', 'allowLocalFacilitator must be a boolean.');
    if (input.runtime?.allowLocalFacilitator === true) runtime.allowLocalFacilitator = true;
    if (input.runtime && Object.keys(input.runtime).some(key => !['port', 'facilitator', 'allowLocalFacilitator'].includes(key))) throw problem('INVALID_RUNTIME', 'Use original Python release port and facilitator options only.');
    const label = note(input.label, this.metadata().label).trim();
    const fingerprint = hash(stable({ revisionId: revision.id, id: input.id, label, runtime }));
    let record = this.row('stages', input.id, false);
    if (record && record.fingerprint !== fingerprint) throw problem('STAGE_CONFLICT', 'That native release ID already belongs to another source or runtime request.', 409);
    if (record) {
      try {
        const release = await inspectRelease(this.releaseRoot, input.id);
        if (!this.stageMatches(record, release)) throw problem('STAGE_CONFLICT', 'That native release ID contains different retained source.', 409);
        record = { ...record, status: 'STAGED', digest: release.digest, release, error: null, completedAt: record.completedAt ?? now() };
        this.put('stages', record); return record;
      } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (record.status === 'STAGING' && record.owner?.host === hostname() && processAlive(record.owner.pid))
        throw problem('STAGE_BUSY', 'This saved release is currently being staged. Refresh its retained status.', 409);
    } else {
      try { await inspectRelease(this.releaseRoot, input.id); throw problem('STAGE_CONFLICT', 'That original release ID already exists. Choose a new release ID.', 409); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
    const materialized = await this.materialize(revision.id);
    try {
      const prepared = await preparePythonRelease(materialized.config, { sourceRoot: materialized.pythonRoot });
      record = { id: input.id, revisionId: revision.id, releaseId: input.id, label, runtime, fingerprint,
        status: 'STAGING', createdAt: record?.createdAt ?? now(), startedAt: now(), completedAt: null,
        digest: null, expected: prepared.python, error: null, owner: this.owner };
      this.transaction(() => {
        const previous = this.row('stages', input.id, false);
        if (previous && previous.fingerprint !== fingerprint) throw problem('STAGE_CONFLICT', 'Another source was assigned this release ID.', 409);
        if (previous?.status === 'STAGING' && previous.owner?.host === hostname() && processAlive(previous.owner.pid))
          throw problem('STAGE_BUSY', 'Another operation is staging this release ID.', 409);
        this.put('stages', record);
      });
      try {
        const release = await stageRelease(this.releaseRoot, { id: input.id, label, python: materialized.config,
          ...(materialized.pythonRoot ? { pythonRoot: materialized.pythonRoot } : {}), runtime });
        if (!this.stageMatches(record, release)) throw problem('STAGE_SOURCE_CHANGED', 'The staged original source differs from the saved preparation.');
        record = { ...record, status: 'STAGED', digest: release.digest, completedAt: now(), release };
        this.put('stages', record); return record;
      } catch (error) { this.put('stages', { ...record, status: 'FAILED', error: errorRecord(error) }); throw error; }
    } finally { await materialized.close(); }
  }
  async state() {
    this.recoverPreviews();
    const metadata = this.metadata();
    const release = await releaseStatus(this.releaseRoot);
    return { schema: WORKSPACE_SCHEMA, workspace: { ...metadata, directory: this.root }, revision: this.revision(metadata.head),
      revisions: this.rows('revisions').map(revisionSummary), previews: this.rows('previews').map(previewSummary),
      staged: this.rows('stages').map(({ owner, expected, fingerprint, ...record }) => record),
      release: { ...release, managed: this.managed ? { instanceId: this.managed.observation.instanceId } : null, lastError: this.lastError },
      customerExports: this.rows('customers').map(({ owner, fingerprint, ...record }) => ({ ...record, directory: join(this.root, 'customer-exports', record.id) })) };
  }
  async diff(from, to) { return compareReleases(this.releaseRoot, from, to); }
  async activate(input) {
    this.writable(); await activateRelease(this.releaseRoot, input.id, { expectedGeneration: input.expectedGeneration, reason: input.reason }); return this.state();
  }
  async rollback(input) {
    this.writable(); await rollbackRelease(this.releaseRoot, { to: input.to, expectedGeneration: input.expectedGeneration, reason: input.reason }); return this.state();
  }
  async run(input) {
    this.writable();
    if (this.managed) throw problem('RELEASE_BUSY', 'This console already owns a seller. Restart it to run the selected release.', 409);
    if (!Number.isSafeInteger(input.expectedGeneration)) throw problem('GENERATION_REQUIRED', 'Supply the current release selection generation.');
    const session = await runActiveRelease(this.releaseRoot, { expectedGeneration: input.expectedGeneration, handleSignals: false });
    this.managed = session;
    session.completion.then(() => { if (this.managed === session) this.managed = null; }, error => {
      this.lastError = errorRecord(error); if (this.managed === session) this.managed = null;
    });
    return this.state();
  }
  requireManaged(instanceId) {
    if (!this.managed || this.managed.observation.instanceId !== instanceId)
      throw problem('RELEASE_NOT_OWNED', 'This console does not own that running seller instance. Refresh its status.', 409);
    return this.managed;
  }
  async stop(input) {
    this.writable(); const session = this.requireManaged(input.instanceId); await session.close();
    if (this.managed === session) this.managed = null; return this.state();
  }
  async restart(input) {
    this.writable(); this.requireManaged(input.instanceId);
    if ((await readReleaseState(this.releaseRoot)).generation !== input.expectedGeneration) throw problem('RELEASE_CONFLICT', 'The selected release changed. Refresh before restarting.', 409);
    await this.stop(input); return this.run(input);
  }
  async exportCustomer(input) {
    this.writable(); object(input); releaseId(input.id);
    const previous = this.row('customers', input.id, false);
    if (previous) {
      if (previous.instanceId !== input.instanceId) throw problem('EXPORT_CONFLICT', 'That customer export belongs to another running seller instance.', 409);
      if (previous.status === 'COMPLETED') return { ...previous, directory: join(this.root, 'customer-exports', input.id) };
      throw problem('EXPORT_INCOMPLETE', 'That create-only export has an incomplete retained outcome. Inspect it and choose another export ID.', 409);
    }
    const session = this.requireManaged(input.instanceId), status = await releaseStatus(this.releaseRoot);
    if (!['RUNNING', 'RESTART_REQUIRED'].includes(status.runtime.state) || status.runtime.observed?.instanceId !== input.instanceId)
      throw problem('SELLER_UNAVAILABLE', 'The original running seller readback is unavailable. Refresh before exporting its client.', 409);
    if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(session.url)) throw problem('INVALID_LISTENER', 'Use the original owned loopback seller listener.');
    let record = { id: input.id, instanceId: input.instanceId, releaseId: session.release.id, releaseDigest: session.release.digest,
      createdAt: now(), status: 'RUNNING', files: [], error: null, owner: this.owner };
    this.transaction(() => {
      if (this.row('customers', input.id, false)) throw problem('EXPORT_CONFLICT', 'Another operation claimed that export ID.', 409);
      this.put('customers', record);
    });
    const temporary = join(this.root, 'operations', 'customer-' + randomUUID());
    try {
      await mkdir(temporary, { mode: 0o700 });
      const response = await fetch(session.url + '/_seller/openapi.json', { redirect: 'error', signal: AbortSignal.timeout(10000) });
      if (!response.ok) throw problem('SELLER_UNAVAILABLE', 'The original seller OpenAPI did not answer successfully.');
      const chunks = []; let total = 0;
      for await (const chunk of response.body) { total += chunk.length; if (total > 16 * MiB) throw problem('OPENAPI_LIMIT', 'Original seller OpenAPI exceeds the native client export limit.'); chunks.push(chunk); }
      this.requireManaged(input.instanceId);
      const openapi = join(temporary, 'seller-openapi.json'); await writeNew(openapi, Buffer.concat(chunks));
      const exported = await exportSellerClient({ openapi, out: join(this.root, 'customer-exports', input.id) });
      const fileRecords = [];
      for (const name of exported.files) { sourcePath(name); const bytes = await regular(join(exported.directory, name), 32 * MiB); fileRecords.push({ path: name, bytes: bytes.length, sha256: hash(bytes) }); }
      record = { ...record, ...exported, id: input.id, status: 'COMPLETED', completedAt: now(), fileRecords };
      this.put('customers', record); return record;
    } catch (error) { this.put('customers', { ...record, status: 'FAILED', error: errorRecord(error) }); throw error; }
    finally { await rm(temporary, { recursive: true, force: true }); }
  }
  async customerFile(id, file) {
    const record = this.row('customers', id); sourcePath(file);
    const expected = record.fileRecords?.find(item => item.path === file);
    if (!expected) throw problem('NOT_FOUND', 'That file is not part of this retained original client export.', 404);
    const bytes = await regular(join(this.root, 'customer-exports', id, file), 32 * MiB);
    if (hash(bytes) !== expected.sha256 || bytes.length !== expected.bytes) throw problem('EXPORT_CHANGED', 'The retained customer client bytes changed.');
    return { bytes, sha256: expected.sha256, contentType: file.endsWith('.json') ? 'application/json' : 'text/plain; charset=utf-8' };
  }
  async exportBundle() {
    const snapshot = this.transaction(() => ({ metadata: this.metadata(), revisions: this.rows('revisions'), previews: this.rows('previews'), stages: this.rows('stages'), customers: this.rows('customers') }));
    const blobs = new Map(); let total = 0;
    const add = bytes => {
      const sha256 = hash(bytes);
      if (!blobs.has(sha256)) {
        total += bytes.length;
        if (total > MAX_BUNDLE_BYTES * 0.7) throw problem('BUNDLE_LIMIT', 'This portable JSON export exceeds 256 MiB. All saved workspace data remains available in its local directory.');
        blobs.set(sha256, { sha256, bytes: bytes.length, base64: bytes.toString('base64') });
      }
      return { sha256, bytes: bytes.length };
    };
    for (const revision of snapshot.revisions) for (const file of revision.files) if (!blobs.has(file.sha256)) add(await this.blob(file.sha256));
    for (const preview of snapshot.previews) if (preview.result && !blobs.has(preview.result.sha256)) add(await this.blob(preview.result.sha256));
    const state = await readReleaseState(this.releaseRoot), catalog = await listReleases(this.releaseRoot), releases = [];
    if (catalog.errors.length) throw problem('RELEASE_EXPORT_ERROR', 'Repair the original release store errors before exporting it: ' + JSON.stringify(catalog.errors));
    for (const release of catalog.releases) {
      await inspectRelease(this.releaseRoot, release.id);
      const path = join(this.releaseRoot, 'releases', release.id), recordBytes = await regular(join(path, 'release.json'), 4 * MiB), record = JSON.parse(recordBytes);
      const files = [{ path: 'release.json', ...add(recordBytes) }];
      for (const file of record.files) {
        sourcePath(file.file); const bytes = await regular(join(path, file.file), 32 * MiB);
        if (bytes.length !== file.bytes || hash(bytes) !== file.sha256) throw problem('RELEASE_CHANGED', 'An original immutable release changed while it was being exported.');
        files.push({ path: file.file, ...add(bytes) });
      }
      releases.push({ id: release.id, files });
    }
    const customerFiles = [];
    for (const customer of snapshot.customers) {
      if (customer.status !== 'COMPLETED') continue;
      const files = [];
      for (const file of customer.fileRecords) files.push({ path: file.path, ...add((await this.customerFile(customer.id, file.path)).bytes) });
      customerFiles.push({ id: customer.id, files });
    }
    const payload = { schema: EXPORT_SCHEMA, createdAt: now(), workspace: snapshot, releaseStore: { state, releases }, customerFiles,
      blobs: [...blobs.values()].sort((a, b) => a.sha256.localeCompare(b.sha256)) };
    const bytes = formatted(payload);
    if (bytes.length > MAX_BUNDLE_BYTES) throw problem('BUNDLE_LIMIT', 'This portable JSON export exceeds 256 MiB. All saved workspace data remains in its local directory.');
    return { bytes, sha256: hash(bytes), filename: this.metadata().id + '.python-workspace.json' };
  }
  close() {
    if (this.closing) return this.closing;
    this.closing = (async () => {
      for (const active of this.jobs.values()) active.controller.abort(new Error('Workspace shutdown.'));
      const jobs = [...this.jobs.values()].map(active => active.completion);
      const results = await Promise.allSettled(jobs);
      let failure = results.find(result => result.status === 'rejected')?.reason;
      if (this.managed) { try { await this.managed.close(); } catch (error) { failure ??= error; } this.managed = null; }
      try { this.db.close(); } finally { this.closed = true; }
      if (failure) throw failure;
    })();
    return this.closing;
  }
}

/** Reopen a portable saved workspace in a new directory. No Python, seller or old PID is started. */
export async function importWorkspace(root, bundle) {
  root = resolve(root);
  const bytes = typeof bundle === 'string' ? await regular(resolve(bundle), MAX_BUNDLE_BYTES) : Buffer.isBuffer(bundle) ? bundle : formatted(bundle);
  if (bytes.length > MAX_BUNDLE_BYTES) throw problem('BUNDLE_LIMIT', 'Portable workspace exceeds its 256 MiB limit.');
  const input = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
  if (input.schema !== EXPORT_SCHEMA) throw problem('INVALID_BUNDLE', 'Expected an original Python workspace export.');
  object(input.workspace); object(input.workspace.metadata);
  if (input.workspace.metadata.schema !== WORKSPACE_SCHEMA || !Array.isArray(input.blobs) || !Array.isArray(input.releaseStore?.releases) || !Array.isArray(input.customerFiles)) throw problem('INVALID_BUNDLE', 'Portable workspace structure is incomplete.');
  for (const table of TABLES) if (!Array.isArray(input.workspace[table])) throw problem('INVALID_BUNDLE', 'Portable workspace is missing ' + table + '.');
  const blobs = new Map();
  for (const file of input.blobs) {
    digest(file.sha256);
    if (blobs.has(file.sha256) || typeof file.base64 !== 'string' || !Number.isSafeInteger(file.bytes) || file.bytes < 0) throw problem('INVALID_BUNDLE', 'Portable content blobs must have unique digests and valid sizes.');
    const data = Buffer.from(file.base64, 'base64');
    if (data.length !== file.bytes || hash(data) !== file.sha256) throw problem('INVALID_BUNDLE', 'Portable content bytes differ from their retained SHA-256 digest.');
    blobs.set(file.sha256, data);
  }
  const retained = descriptor => {
    digest(descriptor.sha256); const data = blobs.get(descriptor.sha256);
    if (!data || data.length !== descriptor.bytes) throw problem('INVALID_BUNDLE', 'A portable file references missing or differently sized content.');
    return data;
  };
  const revisions = new Map();
  for (const revision of input.workspace.revisions) {
    identifier(revision.id); authoredPath(revision.entry);
    if (revisions.has(revision.id) || !Array.isArray(revision.files) || !revision.files.length || revision.files.length > 512 || typeof revision.declarationText !== 'string' || Buffer.byteLength(revision.declarationText) > MiB) throw problem('INVALID_BUNDLE', 'A saved revision is incomplete or duplicated.');
    const paths = new Set(); let total = 0;
    for (const file of revision.files) { authoredPath(file.path); const data = retained(file); if (paths.has(file.path) || data.length > FILE_LIMIT) throw problem('INVALID_BUNDLE', 'Revision source paths must be unique and fit the original source limit.'); paths.add(file.path); total += data.length; }
    if (!paths.has(revision.entry) || !revision.entry.endsWith('.py') || revision.files.find(file => file.path === revision.entry).bytes > 2 * MiB || total > SOURCE_LIMIT ||
        revision.declarationSourcePath !== null && !paths.has(revision.declarationSourcePath)) throw problem('INVALID_BUNDLE', 'Revision entry, declaration source or source size is inconsistent.');
    const expected = hash(stable({ entry: revision.entry, declarationText: revision.declarationText, declarationSourcePath: revision.declarationSourcePath, sourceScope: revision.sourceScope, files: revision.files }));
    if (revision.digest !== expected) throw problem('INVALID_BUNDLE', 'The immutable revision digest differs from its source records.');
    revisions.set(revision.id, revision);
  }
  if (!revisions.has(input.workspace.metadata.head)) throw problem('INVALID_BUNDLE', 'Portable workspace head does not refer to a saved revision.');
  for (const revision of revisions.values()) if (revision.parent !== null && !revisions.has(revision.parent)) throw problem('INVALID_BUNDLE', 'Saved revision history is incomplete.');
  for (const preview of input.workspace.previews) {
    identifier(preview.id); if (!revisions.has(preview.revisionId)) throw problem('INVALID_BUNDLE', 'A retained preview is missing its saved source revision.');
    if (preview.result) retained(preview.result);
  }
  await mkdir(root, { mode: 0o700 }); let workspace;
  try {
    for (const name of ['blobs', 'operations', 'customer-exports']) await mkdir(join(root, name), { mode: 0o700 });
    await writeNew(join(root, 'workspace.sqlite3'), Buffer.alloc(0));
    await initReleaseStore(join(root, 'release-store'));
    for (const [sha256, data] of blobs) await writeNew(join(root, 'blobs', sha256), data);
    const db = makeDatabase(join(root, 'workspace.sqlite3')); workspace = new PythonWorkspace(root, db);
    const metadata = { ...input.workspace.metadata, importedAt: now(), importSha256: hash(bytes),
      origin: { ...input.workspace.metadata.origin, refreshAvailable: false } };
    db.prepare('INSERT INTO metadata(id,value) VALUES(1,?)').run(JSON.stringify(metadata));
    workspace.transaction(() => {
      for (const table of TABLES) {
        const seen = new Set();
        for (const original of [...input.workspace[table]].reverse()) {
          identifier(original.id); if (seen.has(original.id)) throw problem('INVALID_BUNDLE', 'Duplicate retained record: ' + original.id); seen.add(original.id);
          let record = { ...original };
          if (table === 'previews' && INFLIGHT.has(record.status)) record = { ...record, status: 'INTERRUPTED', endedAt: now(), error: { code: 'PREVIEW_IMPORTED', message: 'The archive contains an unfinished preview. Import retained its input and source without executing it again.' } };
          if (table === 'stages' && record.status === 'STAGING') record = { ...record, status: 'INTERRUPTED' };
          if (table === 'customers' && record.status === 'RUNNING') record = { ...record, status: 'FAILED', error: { code: 'EXPORT_IMPORTED', message: 'The archive retained an incomplete customer export.' } };
          delete record.owner; workspace.put(table, record);
        }
      }
    });
    const ids = new Set();
    for (const release of input.releaseStore.releases) {
      releaseId(release.id); if (ids.has(release.id)) throw problem('INVALID_BUNDLE', 'Duplicate native release.'); ids.add(release.id);
      const path = join(workspace.releaseRoot, 'releases', release.id); await mkdir(path, { mode: 0o700 }); const paths = new Set();
      for (const file of release.files) { sourcePath(file.path); if (paths.has(file.path) || ['pilot-runtime.json', 'readiness.json'].includes(file.path)) throw problem('INVALID_BUNDLE', 'Duplicate or live-runtime file in immutable release export.'); paths.add(file.path); await privateParents(path, file.path); await writeNew(join(path, file.path), retained(file)); }
      await inspectRelease(workspace.releaseRoot, release.id);
    }
    await atomic(join(workspace.releaseRoot, 'state.json'), formatted(input.releaseStore.state));
    const selected = await readReleaseState(workspace.releaseRoot);
    if (selected.active !== null && !ids.has(selected.active) || selected.previous !== null && !ids.has(selected.previous)) throw problem('INVALID_BUNDLE', 'The native release selection references a missing immutable release.');
    for (const stage of workspace.rows('stages')) {
      if (!revisions.has(stage.revisionId)) throw problem('INVALID_BUNDLE', 'A staged release is missing its authoring source revision.');
      if (stage.status === 'STAGED') {
        const native = await inspectRelease(workspace.releaseRoot, stage.releaseId);
        if (stage.digest !== native.digest || !workspace.stageMatches(stage, native)) throw problem('INVALID_BUNDLE', 'The original native release differs from its authoring stage record.');
      }
    }
    const customerIds = new Set();
    for (const customer of input.customerFiles) {
      releaseId(customer.id); if (customerIds.has(customer.id)) throw problem('INVALID_BUNDLE', 'Duplicate original customer export.'); customerIds.add(customer.id);
      const record = workspace.row('customers', customer.id), path = join(root, 'customer-exports', customer.id); await mkdir(path, { mode: 0o700 });
      const expected = new Map((record.fileRecords ?? []).map(file => [file.path, file]));
      for (const file of customer.files) { sourcePath(file.path); const original = expected.get(file.path); if (!original || original.sha256 !== file.sha256 || original.bytes !== file.bytes) throw problem('INVALID_BUNDLE', 'Customer export members differ from their original file records.'); expected.delete(file.path); await privateParents(path, file.path); await writeNew(join(path, file.path), retained(file)); }
      if (expected.size) throw problem('INVALID_BUNDLE', 'An original customer export file is missing.');
    }
    for (const customer of workspace.rows('customers')) if (customer.status === 'COMPLETED' && !customerIds.has(customer.id)) throw problem('INVALID_BUNDLE', 'A completed customer export is missing its original file set.');
    await workspace.reconcileStages(); await syncDirectory(root); return workspace;
  } catch (error) { await workspace?.close().catch(() => {}); await rm(root, { recursive: true, force: true }); throw error; }
}
