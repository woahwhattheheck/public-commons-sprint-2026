#!/usr/bin/env node
// MIT. The original generated client authors requests; SF88 owns all durable work.
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { sourceRoot, nativePath, nativeImport, readJson, createJson, sha256, argumentsMap, required } from './runtime.mjs';

const HELP = `GoldRush customer workflow (Node 22+)
  request --release DIR --operation balances|transfers --inputs INPUTS.json
    --intent STABLE_ID --accept INDEX --max-atomic DECIMAL --out NEW_CONFIG.json
    [--payment-flow authorization|upfront] [--source-root CHECKOUT]
  prepare --state PRIVATE_DIRECTORY --workspace OPERATOR_DIRECTORY [--config CONFIG.json] [--source-root CHECKOUT]
  prepare --config CONFIG.json --state PRIVATE_DIRECTORY [--profile OPERATOR_PROFILE.json] [--source-root CHECKOUT]
  review|execute|recover --state PRIVATE_DIRECTORY --intent STABLE_ID [--source-root CHECKOUT]
  next-page --state PRIVATE_DIRECTORY --intent PREVIOUS_ID --next-intent NEW_ID
    --max-atomic DECIMAL --out NEW_CONFIG.json [--source-root CHECKOUT]

request and prepare are offline. Only execute starts the original operator flow.
recover reads the same saved result. next-page authors one request only after a
successful retained transfers page; it never executes or retries a purchase.`;

async function request(options, root) {
  const release = resolve(required(options, '--release'));
  const manifest = (await readJson(join(release, 'release.json'))).value;
  if (manifest.schema !== 'stellar-forge.goldrush-release.v1' || manifest.customer?.client !== 'customer/seller-client.mjs')
    throw new TypeError('Use this provider release and its original generated client');
  const clientPath = join(release, manifest.customer.client);
  const { readFile } = await import('node:fs/promises');
  if (sha256(await readFile(clientPath)) !== manifest.customer.clientSha256) throw new TypeError('Generated client changed');
  // This is a trusted local module generated by the original SF30 compiler.
  const client = await import(pathToFileURL(clientPath).href);
  const selected = required(options, '--operation');
  if (!['balances','transfers'].includes(selected)) throw new TypeError('Select balances or transfers');
  const id = 'goldrush-' + selected, inputs = (await readJson(required(options, '--inputs'), 65536)).value;
  const index = Number(required(options, '--accept'));
  if (!/^(0|[1-9][0-9]*)$/.test(options.get('--accept')) || !Number.isSafeInteger(index)) throw new TypeError('Explicit nonnegative accept index required');
  const built = client.buildRequest(id, inputs, { intentId: required(options, '--intent'),
    acceptIndex: index, maxAtomic: required(options, '--max-atomic'),
    ...(options.has('--payment-flow') ? {paymentFlow:options.get('--payment-flow')} : {}) });
  const selectedOperation = client.operations.find(operation => operation.id === id);
  const { createLiveRequestAdmission } = await nativeImport(root, 'sf89-live-request-admission/index.mjs');
  const decision = createLiveRequestAdmission(selectedOperation.offer)({ method: 'GET',
    pathParams: inputs.path, query: inputs.query ?? {} });
  if (decision !== true) throw new TypeError('Original merchant input admission rejected this request: ' + (decision.body?.error ?? 'INVALID_INPUT'));
  await createJson(resolve(required(options, '--out')), { operation: built });
  return { status: 'ORIGINAL_REQUEST_AUTHORED', intentId: built.intentId, url: built.url,
    expect: built.expect, config: resolve(options.get('--out')), paymentsInitiated: 0 };
}

async function retainedPage(operation, result) {
  result.raiseForStatus();
  const wire = await result.json({ limit: 1048576 }); // Original SDK verifies saved hash first.
  const { operation: input } = (await readJson(operation.configPath)).value;
  const url = new URL(input.url), pieces = url.pathname.split('/');
  if (wire?.error !== false || !wire.data || !Array.isArray(wire.data.items) ||
      typeof wire.data.address !== 'string' || wire.data.address.toLowerCase() !== pieces[4]?.toLowerCase() ||
      wire.data.chain_name !== pieces[2]) throw new TypeError('Provider result does not match the retained wallet request');
  const data = wire.data;
  return { wire, input, url, data };
}

async function consume(operation, result) {
  if (result === null) return { status: 'ORIGINAL_RESULT_NOT_RECORDED', intentId: operation.intentId, retry: 'NO_AUTOMATIC_RETRY' };
  const output = { intentId: operation.intentId, status: result.status, httpStatus: result.native.httpStatus,
    delivery: result.delivery, ok: result.ok, runtimeError: result.record.runtimeError,
    providerRead: { status: 'NOT_READ' }, retry: 'NO_AUTOMATIC_RETRY' };
  if (result.ok && result.delivery.status === 'SAVED') {
    try {
      const { data } = await retainedPage(operation, result);
      output.page = { address: data.address, chain: data.chain_name, updatedAt: data.updated_at,
        items: data.items.length, pagination: data.pagination ?? null };
      output.providerRead = { status: 'READ' };
      // Token balance quantities remain decimal strings in the verified response.
    } catch (error) {
      // Interpretation cannot replace the original terminal/delivery outcome.
      output.providerRead = { status: 'FAILED', code:
        typeof error?.code === 'string' && /^[A-Z][A-Z0-9_]{0,79}$/.test(error.code)
          ? error.code : 'GOLDRUSH_RETAINED_RESPONSE_INVALID' };
    }
  }
  return output;
}

export async function main(args = process.argv.slice(2)) {
  if (!args.length || args[0] === '--help') { process.stdout.write(HELP + '\n'); return; }
  const action = args[0], allowed = {
    request: ['--release','--operation','--inputs','--intent','--accept','--max-atomic','--payment-flow','--out','--source-root'],
    prepare: ['--config','--workspace','--state','--profile','--source-root'],
    review: ['--state','--intent','--source-root'], execute: ['--state','--intent','--source-root'], recover: ['--state','--intent','--source-root'],
    'next-page': ['--state','--intent','--next-intent','--max-atomic','--out','--source-root'],
  };
  if (!allowed[action]) throw new TypeError(HELP);
  const options = argumentsMap(args.slice(1), allowed[action]), root = sourceRoot(options.get('--source-root'));
  let output;
  if (action === 'request') output = await request(options, root);
  else {
    const { Buyer } = await nativeImport(root, 'sf88-operator-buyer-cli/node/index.mjs');
    const buyer = new Buyer({ runtimeDirectory: nativePath(root, 'sf88-operator-buyer-cli'),
      stateDirectory: resolve(required(options, '--state')),
      ...(options.has('--profile') ? { operatorProfile: resolve(options.get('--profile')) } : {}) });
    if (action === 'prepare' && options.has('--workspace') && options.has('--profile'))
      throw new TypeError('An explicit workspace supplies its own original operator profile');
    const capture = { responseFile: { maxBytes: 1048576, timeoutMs: 30000,
      expectedContentType: 'application/json' }, requestTimeoutMs: 90000 };
    const operation = action === 'prepare'
      ? options.has('--workspace')
        ? await buyer.fromWorkspace(resolve(options.get('--workspace')), {
          ...capture, configuration: options.has('--config') ? resolve(options.get('--config')) : undefined })
        : await buyer.fromConfig(resolve(required(options, '--config')), capture)
      : buyer.operation(required(options, '--intent'));
    if (action === 'prepare' || action === 'review') output = await operation.review();
    else if (action === 'next-page') {
      const result = await operation.recover();
      if (!result) throw new TypeError('A retained successful transfers page is required');
      const { input, url, data } = await retainedPage(operation, result);
      if (!url.pathname.endsWith('/transfers_v2')) throw new TypeError('Only transfers have page continuation');
      const page = data.pagination, oldPage = Number(url.searchParams.get('page-number')), size = Number(url.searchParams.get('page-size'));
      if (url.searchParams.getAll('page-number').length !== 1 || url.searchParams.getAll('page-size').length !== 1 ||
          !Number.isSafeInteger(oldPage) || oldPage < 0 || !Number.isSafeInteger(size) || size < 1 || size > 100 ||
          !page || !Number.isSafeInteger(page.page_number) || !Number.isSafeInteger(page.page_size) ||
          typeof page.has_more !== 'boolean' || page.page_number !== oldPage || page.page_size !== size)
        throw new TypeError('Provider pagination does not match the exact retained request');
      if (!page.has_more) output = { status: 'NO_MORE_PAGES_ADVERTISED', intentId: operation.intentId, paymentsInitiated: 0 };
      else {
        if (oldPage >= Number.MAX_SAFE_INTEGER) throw new TypeError('Page index exceeds the native integer range');
        const nextIntent = required(options, '--next-intent'), ceiling = required(options, '--max-atomic');
        if (nextIntent === operation.intentId) throw new TypeError('A new page requires a new explicit intent');
        url.searchParams.set('page-number', String(oldPage + 1));
        const next = { ...input, url: url.href, intentId: nextIntent, expect: { ...input.expect, maxAtomic: ceiling } };
        const { operation: validateOperation } = await nativeImport(root, 'sf88-operator-buyer-cli/config.mjs');
        validateOperation(next);
        await createJson(resolve(required(options, '--out')), { operation: next });
        output = { status: 'NEXT_PAGE_AUTHORED_NOT_EXECUTED', intentId: nextIntent, page: oldPage + 1,
          config: resolve(options.get('--out')), paymentsInitiated: 0 };
      }
    } else output = await consume(operation, action === 'execute'
      ? await operation.execute({ review: await operation.review() }) : await operation.recover());
  }
  process.stdout.write(JSON.stringify(output, null, 2) + '\n');
  return output;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  main().catch(error => { process.stderr.write((error?.code ?? (error instanceof TypeError ? error.message : 'GOLDRUSH_CUSTOMER_FAILED')) + '\n'); process.exitCode = 1; });
