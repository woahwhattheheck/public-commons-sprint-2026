/* Native host adapter: original authorization, task queue and file tickets. */
const READS = new Set(['list','get','frontier.progress','campaign.get','campaign.list','campaign.history','capabilities','source.catalog']);
let componentReady;
function component() {
  // The component is derived from the same shipped legacy entry, with external
  // CSS. No inline-script/style exemptions are added to the operator CSP.
  globalThis.__ecoMonitoringNativeHost = true;
  return componentReady ||= import('./monitoring-component.mjs');
}
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));

export function attachMonitoring({getState, api, endpoint, showTask, toast}) {
  const nodes = new Map(), pendingMemory = new Map();
  const storage = {
    get(key) {
      try { return sessionStorage.getItem(key); }
      catch { return pendingMemory.get(key) || null; }
    },
    set(key, value) {
      pendingMemory.set(key, value);
      try { sessionStorage.setItem(key, value); } catch {}
    },
    remove(key) {
      pendingMemory.delete(key);
      try { sessionStorage.removeItem(key); } catch {}
    }
  };
  let active = null, generation = 0, lastCompleted = null, updating = false;
  function workspace() {const key = getState()?.workspace_key;if(!key)throw Error('Select an original workspace.');return key;}
  async function transport(key, action, payload={}) {
    if(READS.has(action))return api('/api/monitoring?'+new URLSearchParams({workspace:key,action,payload:JSON.stringify(payload)}));
    const request={workspace:key,action:'monitoring.'+action,payload:{...payload}};
    // A failed HTTP exchange must retry the original campaign mutation, not the
    // new UUID generated by the form's next click with otherwise identical input.
    const campaignMutation=action.startsWith('campaign.');
    if(campaignMutation)delete request.payload.operation_id;
    const raw=new TextEncoder().encode(JSON.stringify(request));
    const hash=[...new Uint8Array(await crypto.subtle.digest('SHA-256',raw))].map(x=>x.toString(16).padStart(2,'0')).join('');
    const storedKey='eco-monitoring-request:'+key+':'+hash;
    let pending;
    try {pending=JSON.parse(storage.get(storedKey)||'null');} catch {pending=null;}
    if(!pending){pending={operation_id:crypto.randomUUID()};storage.set(storedKey,JSON.stringify(pending));}
    if(campaignMutation)request.payload.operation_id=pending.operation_id;
    let task=await api('/api/actions',{method:'POST',body:{...request,operation_id:pending.operation_id}});
    pending.task_id=task.id;storage.set(storedKey,JSON.stringify(pending));
    while(['queued','running'].includes(task.state)){
      await wait(600);
      task=await api('/api/task?'+new URLSearchParams({workspace:key,id:task.id}));
    }
    if(task.state!=='complete'){
      showTask?.(task.id);
      throw Error((task.error?.message||`The retained task is ${task.state}.`)+ ' Open its existing task to resume.');
    }
    // Refresh through the original task decorator for authenticated file links.
    task=await api('/api/task?'+new URLSearchParams({workspace:key,id:task.id}));
    storage.remove(storedKey);
    return task.result;
  }
  async function mount(root) {
    const key=workspace(), ticket=++generation;
    await component();
    if(ticket!==generation || workspace()!==key)return;
    let node=nodes.get(key);
    if(!node){node=document.createElement('eco-monitoring');node.transport=(action,payload)=>transport(key,action,payload);nodes.set(key,node);}
    if(active===node && node.parentNode===root)return;
    active=node;root.replaceChildren(node);
  }
  async function update() {
    if (!active?.isConnected || active.busy || updating) return;
    const completed = JSON.stringify((getState()?.tasks || []).filter(task =>
      task.state === 'complete' && (task.action?.startsWith('monitoring.') || task.action?.startsWith('source.'))
    ).map(task => task.id).sort());
    if (completed === lastCompleted) return;
    updating = true;
    try { await active.refresh(); await active.refreshSources(); lastCompleted = completed; }
    finally { updating = false; }
  }
  function detach(){generation++;if(active)active.remove();active=null;}
  return {mount,update,detach,render:()=>'',dispatch:()=>false};
}
