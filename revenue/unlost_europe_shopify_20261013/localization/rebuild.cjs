'use strict';
const fs=require('node:fs'),path=require('node:path');
const {createLocalizationCore}=require('./localization-core.cjs');
const sha=require('./connected_sha256.cjs');
const {localizationHtml}=require('./localization-view.cjs');
const api=createLocalizationCore(sha);
const root=__dirname,out=path.resolve(process.argv[2]||path.join(root,'opened-application.html'));
if(fs.existsSync(out))throw Error('Choose a new output HTML path');
const workspace=api.receive(JSON.parse(fs.readFileSync(path.join(root,'initial-working.json'),'utf8')));
const names=['localization-core.cjs','localization-view.cjs','connected_sha256.cjs','rebuild.cjs','README.txt','initial-working.json'];
const files=names.map(name=>{const content=fs.readFileSync(path.join(root,name),'utf8');return{path:name,content,...sha.sha256Utf8(content)};});
const html=localizationHtml({coreSource:files.find(f=>f.path==='localization-core.cjs').content,shaSource:files.find(f=>f.path==='connected_sha256.cjs').content,workspace,sourceFiles:files,guide:files.find(f=>f.path==='README.txt').content});
fs.writeFileSync(out,html,{flag:'wx',mode:0o600});
process.stdout.write(JSON.stringify({output:out,...sha.sha256Utf8(html),merchants:workspace.selection.leadIds.length,revision:workspace.revision})+'\n');
