import assert from 'node:assert/strict';
import {createMappingTemplate,previewMappingTemplate,applyMappingTemplate,verifyMappingTemplate} from '../operator/web/client_source_mapping.mjs';
const columns = names => names.map((label,index)=>({id:'c'+index,label}));
const part={kind:'table',name:'Parameters',fields:columns(['Land class','N load','P load'])};
const file={filename:'authored-layout.csv',original:{sha256:'a'.repeat(64)},inspection:{parts:[part]}};
const inspection={id:'b'.repeat(64),action:'client-source.inspect',state:'complete',files:[file]};
const choice={role:'BIOPHYSICAL',file_index:0,part_index:0,mapping:{lucode:'c0',load_n:'c1',load_p:'c2'},models:['ndr'],confirmed:true,units:'original reviewed units'};
const template=await createMappingTemplate({name:'Familiar headings',choice,part,file,inspection});
await verifyMappingTemplate(JSON.parse(JSON.stringify(template)));
const reordered={...part,fields:columns(['P load','Land class','N load'])};
assert.deepEqual(previewMappingTemplate(template,reordered).mapping,{lucode:'c1',load_n:'c2',load_p:'c0'});
const missing={...part,fields:columns(['Land class','P load'])};
const applied=applyMappingTemplate({...choice,models:['sdr']},template,missing,['lucode','load_n']);
assert.deepEqual(applied.choice.mapping,{lucode:'c0',load_p:'c1'});
assert.equal(applied.choice.confirmed,false);
assert.equal(applied.choice.units,choice.units);
assert.deepEqual(applied.choice.models,['sdr']);
assert.deepEqual(applied.preview.missing_required,['load_n']);
const duplicate={...part,fields:columns(['Land class','N load','N load','P load'])};
assert.equal(previewMappingTemplate(template,duplicate).rows.find(x=>x.parameter==='load_n').status,'ambiguous-current-header');
const duplicatePart={...part,fields:columns(['Land class','N load','N load'])};
const duplicateFile={...file,inspection:{parts:[duplicatePart]}};
const duplicateTemplate=await createMappingTemplate({name:'Repeated source',choice:{...choice,mapping:{load_n:'c1'}},part:duplicatePart,file:duplicateFile,inspection:{...inspection,files:[duplicateFile]}});
assert.equal(previewMappingTemplate(duplicateTemplate,reordered).rows[0].status,'ambiguous-original-header');
const blankPart={...part,fields:columns([''])},blankFile={...file,inspection:{parts:[blankPart]}};
const blankTemplate=await createMappingTemplate({name:'Blank source',choice:{...choice,mapping:{load_n:'c0'}},part:blankPart,file:blankFile,inspection:{...inspection,files:[blankFile]}});
assert.equal(previewMappingTemplate(blankTemplate,{...part,fields:columns([''])}).rows[0].status,'blank-original-header');
assert.throws(()=>applyMappingTemplate(choice,template,{...part,fields:columns(['Unrelated'])}),/No unambiguous/);
await assert.rejects(verifyMappingTemplate({...template,name:'Changed without new identity'}),/differs from its retained identity/);
console.log(JSON.stringify({reordered:true,missing:true,duplicate_current:true,duplicate_original:true,blank_header:true,scientific_choices_preserved:true,stale_mapping_removed:true,identity_change_detected:true}));
