"""Receive one existing completed observed timeline through the original Study path.

This is an operating continuation, not a numerical experiment. It prepares the
original Scientific Reports source, exports the selected editable Study, restores
it with model.portable and reopens it in a separate process using the copied app.
"""
from __future__ import annotations
import argparse
from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import traceback
from .common import atomic_json, digest, file_digest, held, identifier, now, read_json, verify_file
from .workspace import Workspace
from . import landcover_workspace, landcover_report_source, scientific_report_editions
from . import study_transfer, portable

SCHEMA = "upstate.landcover-timeline-study-receiving/v1"
IMPLEMENTATION = (
    "model/landcover_timeline_study_receiving.py",
    "model/landcover_study_transfer.py",
    "model/landcover_report_source.py",
    "model/scientific_report_editions.py",
    "model/study_transfer.py",
    "model/portable.py",
)


def _regular(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError("Keep original receiving members as ordinary files: " + str(path))
    return path


def _pin(path):
    path = _regular(path)
    return {"bytes": path.stat().st_size, "sha256": file_digest(path)}


def _tree(root):
    """Stream every original file; preserve original names and complete membership."""
    root = Path(root)
    if root.is_symlink() or not root.is_dir():
        raise ValueError("Original artifact directory is absent or linked: " + str(root))
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError("Original artifact tree contains a linked member: " + str(path))
        if path.is_file():
            result[path.relative_to(root).as_posix()] = _pin(path)
        elif not path.is_dir():
            raise ValueError("Original artifact tree contains a non-file member: " + str(path))
    return result


def _same(actual, expected, message):
    if actual != expected:
        raise ValueError(message)


def _write(path, value):
    atomic_json(Path(path), value)


def _keep(path, value):
    if path.exists():
        _same(read_json(_regular(path)), value, "Saved receiving stage differs: " + path.name)
    else:
        atomic_json(path, value, immutable=True)
    return value


def _implementation(application):
    return {name: _pin(application / name) for name in IMPLEMENTATION}


def _snapshot(workspace, ledger_id):
    state = landcover_workspace.inspect(workspace, ledger_id)
    edition, binding, report = state["edition"], state["binding"], state["report"]
    selection = binding["selection"]
    if (edition.get("state") != "complete" or report.get("complete") is not True
            or selection.get("input_mode") != "timeline"
            or report.get("timeline", {}).get("schema") != "upstate.landcover-timeline/v1"
            or report.get("options", {}).get("support_scope") != "all"):
        raise ValueError("Select the original existing completed all-observation timeline ledger")
    years = [row["year"] for row in selection["annual_sources"]]
    _same(report["timeline"]["years"], years, "Original selected years changed")
    directory = workspace.root / landcover_workspace.KIND / ledger_id
    # This full tree includes the retained reducer checkpoint and every output.
    # It is never modified or regenerated by this course.
    return {"project": deepcopy(workspace.project), "ledger_id": ledger_id,
            "state": deepcopy(state), "ledger_files": _tree(directory),
            "years": years}


def _source_files(workspace, source):
    expected = {}
    for item in [*source["files"].values(), *source["members"].values()]:
        path = verify_file(workspace.root, item)
        relative = path.relative_to(workspace.root).as_posix()
        value = {"bytes": item["bytes"], "sha256": item["sha256"]}
        if relative in expected and expected[relative] != value:
            raise ValueError("Original source file identities collide")
        expected[relative] = value
    return expected


def _report_files(workspace, report_id):
    record, directory, operation = scientific_report_editions.inspect(workspace, report_id)
    members = scientific_report_editions.files(record, directory)
    return {
        "record": record, "operation": operation,
        "files": {name: {**descriptor, "workspace_path": (directory / descriptor["path"]).relative_to(
            workspace.root).as_posix()} for name, descriptor in members.items()},
    }


def _verify_files(root, expected):
    for relative, wanted in expected.items():
        path = Path(root) / relative
        if path.resolve().is_relative_to(Path(root).resolve()) is False:
            raise ValueError("Original receiving path escapes its selected root")
        _same(_pin(path), wanted, "Original received member changed: " + relative)


def _selected_ledger_files(manifest, original):
    """Bind cold ledger membership to the original portable archive selection."""
    prefix = "workspace/" + landcover_workspace.KIND + "/" + original["ledger_id"] + "/"
    selected = {}
    for name, descriptor in manifest["members"].items():
        if name.startswith(prefix):
            relative = name[len(prefix):]
            portable.member_name(relative)
            expected = {key: descriptor[key] for key in ("bytes", "sha256")}
            _same(original["ledger_files"].get(relative), expected,
                  "Study ledger member differs from its original snapshot: " + relative)
            selected[relative] = expected
    if not selected:
        raise ValueError("Study omitted the selected original ledger")
    excluded = {}
    for relative, descriptor in original["ledger_files"].items():
        if relative in selected:
            continue
        path = Path(relative)
        reason = None
        if path.name.endswith((".lock", ".pyc", ".pyo")):
            reason = "Original portable lock/compiled-runtime exclusion"
        elif path.name.startswith((".write-", ".intake-", ".archive-",
                                   ".native-reserve-", ".native-recovery-reserve")):
            reason = "Original portable transient-file exclusion"
        else:
            for index, part in enumerate(path.parts[:-1]):
                parent = Path(*path.parts[:index + 1])
                if (part in portable.RUNTIME_DIRECTORIES or part == "source-views"
                        or part.startswith((".archive-", ".receive-", ".write-", ".intake-"))
                        or (parent / "pyvenv.cfg").as_posix() in original["ledger_files"]):
                    reason = "Original portable runtime/materialized-view directory exclusion"
                    break
        if reason is None:
            raise ValueError("Study omitted an original scientific/checkpoint member: " + relative)
        excluded[relative] = {**descriptor, "reason": reason}
    return {"files": selected, "intentional_portable_exclusions": excluded}


def _cold_receive(spec_path, result_path):
    """Executed only by the copied application's module in a separate interpreter."""
    spec = read_json(_regular(spec_path))
    application = Path(spec["application"]).resolve(strict=True)
    actual_application = Path(__file__).resolve().parents[1]
    _same(actual_application, application, "Cold receiving imported another application")
    for module in (landcover_workspace, landcover_report_source, scientific_report_editions, study_transfer, portable):
        if not Path(module.__file__).resolve().is_relative_to(application):
            raise ValueError("Cold receiving imported a producer module outside the copied application")
    _verify_files(application, spec["application_files"])
    workspace = Workspace(spec["workspace"])
    original = spec["original"]
    current = _snapshot(workspace, original["ledger_id"])
    _same({key: value for key, value in current.items() if key != "ledger_files"},
          {key: value for key, value in original.items() if key != "ledger_files"},
          "Cold original ledger state/source/chronology differs")
    _same(current["ledger_files"], spec["ledger_selection"]["files"],
          "Cold ledger differs from the exact archive-selected original members")
    source = landcover_report_source.get(workspace, spec["source"]["id"])
    _same(source, spec["source"], "Cold report-source receipt differs")
    _verify_files(workspace.root, spec["source_files"])
    report = _report_files(workspace, spec["report_id"])
    _same(report, spec["report"], "Cold scientific report or complete attachments differ")
    for descriptor in report["files"].values():
        _same(_pin(workspace.root / descriptor["workspace_path"]),
              {key: descriptor[key] for key in ("bytes", "sha256")},
              "Cold report attachment differs")
    received = study_transfer.verify_received_studies(workspace)
    matched = [row for row in received if row.get("id") == spec["study_id"]]
    if len(matched) != 1 or matched[0].get("identity") != "MATCH":
        raise ValueError("Cold receiving did not reopen the exact selected editable Study")
    result = {
        "schema": SCHEMA, "state": "complete", "project_id": workspace.project["id"],
        "ledger_id": original["ledger_id"], "years": original["years"],
        "signature": original["state"]["report"]["signature"],
        "scientific_report_edition_id": spec["report_id"], "study_id": spec["study_id"],
        "application": str(application), "workspace": str(workspace.root),
        "application_files": len(spec["application_files"]),
        "original_ledger_files": len(original["ledger_files"]),
        "received_ledger_files": len(spec["ledger_selection"]["files"]),
        "intentional_portable_exclusions": spec["ledger_selection"]["intentional_portable_exclusions"],
        "source_files": len(spec["source_files"]), "report_files": report["files"],
        "received_study": matched[0], "original_ledger_unchanged": True,
        "numerical_run_started": False, "browser_started": False,
    }
    _write(result_path, result)
    return result


def run_existing(workspace_path, ledger_id, output, *, title=None, resume=False):
    """Operate one existing ledger; resume only this exact retained continuation."""
    application = Path(__file__).resolve().parents[1]
    workspace = Workspace(Path(workspace_path).resolve(strict=True))
    ledger_id = identifier(ledger_id)
    output = Path(output).absolute()
    if output.is_symlink():
        raise ValueError("Use an ordinary owned receiving output directory")
    # The entire receiving tree must remain outside both original source and data.
    resolved = output.resolve()
    for protected in (application, workspace.root):
        if resolved == protected or resolved.is_relative_to(protected) or protected.is_relative_to(resolved):
            raise ValueError("Receiving output must be separate from original application and Workspace")
    if output.exists():
        if not resume or not output.is_dir():
            raise ValueError("Use a new output directory, or --resume for this exact original course")
    else:
        if resume:
            raise ValueError("The original receiving output does not exist")
        output.mkdir(parents=True, mode=0o700)
        os.chmod(output, 0o700)
    request = {"application": str(application), "workspace": str(workspace.root),
               "ledger_id": ledger_id, "title": title, "implementation": _implementation(application)}
    marker = output / "receiving-request.json"
    with held(output / ".receiving.lock", blocking=False):
        if resume:
            _same(read_json(_regular(marker)), request, "Resume selected another original request or implementation")
        else:
            atomic_json(marker, request, immutable=True)
        state = {"schema": SCHEMA, "state": "running", "request": request,
                 "output": str(output), "started_at": now(), "stages": []}
        state_path = output / "receiving.json"
        events_path = output / "events.jsonl"
        def event(stage, **detail):
            item = {"stage": stage, "at": now(), **detail}
            state["stages"].append(item)
            _write(state_path, state)
            with events_path.open("a", encoding="utf-8") as stream:
                stream.write(json.dumps(item, ensure_ascii=False, allow_nan=False) + "\n")
                stream.flush(); os.fsync(stream.fileno())
            print(json.dumps(item, ensure_ascii=False, allow_nan=False), flush=True)
        original = None
        child = None
        try:
            event("opening_original_ledger")
            original = _snapshot(workspace, ledger_id)
            _keep(output / "original-ledger.json", original)
            event("original_completed_ledger", ledger_id=ledger_id, years=original["years"],
                  signature=original["state"]["report"]["signature"])
            source_spec = {"ledger_id": ledger_id}
            if title is not None:
                source_spec["title"] = title
            event("preparing_original_report_source")
            source_result = landcover_report_source.prepare(workspace, source_spec)
            # prepare may annotate an existing receipt with reused:true; store
            # the immutable source receipt returned by its real get operation.
            source = landcover_report_source.get(workspace, source_result["id"])
            _keep(output / "original-report-source.json", source)
            source_files = _source_files(workspace, source)
            _keep(output / "original-source-files.json", source_files)
            preview_path = output / "original-report-preview.json"
            if preview_path.exists():
                preview = read_json(_regular(preview_path))
            else:
                preview = scientific_report_editions.preview(
                    workspace, {"sources": [source["source"]], "title": source["title"]})
                _keep(preview_path, preview)
            # Reconcile a completed original rendering before retrying its
            # original prepared effect. This uses the selected saved edition.
            report_id = identifier(preview["id"])
            _same(digest(preview["render_identity"]), report_id, "Original report preview identity differs")
            scientific_report_editions.validate_request(
                workspace, {"sources": [source["source"]], "title": source["title"]}, preview["render_identity"])
            if (scientific_report_editions.directory(workspace, report_id) / "edition.json").is_file():
                retained, unused_directory, unused_operation = scientific_report_editions.inspect(workspace, report_id)
                _same(retained["render_identity"], preview["render_identity"], "Completed report belongs to another retained preview")
                rendered = {"scientific_report_edition_id": report_id, "state": "complete"}
            else:
                event("rendering_original_scientific_report", preview_id=report_id)
                rendered = scientific_report_editions.render_prepared(workspace, preview)
            _same(rendered["scientific_report_edition_id"], report_id, "Report result changed the original preview")
            report = _report_files(workspace, report_id)
            _keep(output / "original-scientific-report.json", report)
            report_zip = scientific_report_editions.export(workspace, report_id)
            _keep(output / "original-report-export.json", report_zip)
            event("original_report_complete", scientific_report_edition_id=report_id,
                  files=len(report["files"]))
            selection = {"title": source["title"],
                         "roots": [{"kind": "scientific-report-editions", "id": report_id}],
                         "include_related_results": False}
            plan = study_transfer.preview(workspace, selection)
            _write(output / "study-preview.json", plan)
            selection["preview_token"] = plan["preview_token"]
            archive = output / "timeline-selected-study.zip"
            event("exporting_selected_study", roots=selection["roots"])
            transfer = study_transfer.export_study(
                workspace, archive, selection, progress=lambda detail: event("study_export", detail=detail))
            _write(output / "study-export.json", transfer)
            archive_identity = _pin(archive)
            _same(archive_identity, {key: transfer[key] for key in ("bytes", "sha256")},
                  "Selected Study archive differs from its native receipt")
            _keep(output / "study-archive-identity.json", archive_identity)
            inspected = study_transfer.inspect_transfer_archive(archive, verify=True)
            _same(inspected["study"], transfer["study"], "Selected Study receipt differs inside the archive")
            _same(inspected["study"]["identity"]["selection"], study_transfer.normalise(selection),
                  "Selected Study changed its original report root")
            _same(inspected["manifest"]["project"], workspace.project, "Study belongs to another original project")
            _keep(output / "study-inspection.json", inspected)
            ledger_selection = _selected_ledger_files(inspected["manifest"], original)
            _keep(output / "study-ledger-members.json", ledger_selection)
            application_files = {}
            for name, descriptor in inspected["manifest"]["members"].items():
                if name.startswith("application/"):
                    application_files[name[len("application/"):]] = {
                        key: descriptor[key] for key in ("bytes", "sha256")}
            if not application_files:
                raise ValueError("Selected Study does not contain the complete original application")
            for name in IMPLEMENTATION:
                _same(application_files.get(name), request["implementation"][name],
                      "Selected Study omitted or changed its receiving implementation: " + name)
            destination = output / "received"
            event("receiving_selected_study", destination=str(destination))
            if destination.exists():
                restored = portable.resume_restore(
                    archive, destination, expected_archive_sha256=archive_identity["sha256"])
            else:
                restored = portable.restore(archive, destination)
            _write(output / "original-restore.json", restored)
            _same(restored["archive_sha256"], archive_identity["sha256"], "Restore consumed another archive")
            _same(restored["identity"], "MATCH", "Restore did not return matched identity")
            copied = Path(restored["application"]).resolve(strict=True)
            received_workspace = Path(restored["workspace"]).resolve(strict=True)
            _same(copied, (destination / "application").resolve(), "Restore returned another application")
            _same(received_workspace, (destination / "workspace").resolve(), "Restore returned another Workspace")
            # Exercise the same native completed-receive reconciliation. Do not
            # manufacture an interruption or overwrite the published destination.
            reconciled = portable.resume_restore(
                archive, destination, expected_archive_sha256=archive_identity["sha256"])
            if not reconciled.get("reused_completed_output"):
                raise ValueError("Completed original receiving was not reconciled")
            _write(output / "original-restore-resumed.json", reconciled)
            spec = {
                "application": str(copied), "workspace": str(received_workspace),
                "application_files": application_files, "original": original,
                "ledger_selection": ledger_selection,
                "source": source, "source_files": source_files,
                "report_id": report_id, "report": report, "study_id": transfer["id"],
            }
            spec_path = output / "cold-receive-input.json"
            _keep(spec_path, spec)
            cold_path = output / "cold-receive-result.json"
            _verify_files(copied, application_files)
            bootstrap = (
                "import sys;sys.path.insert(0,sys.argv[1]);"
                "from model.landcover_timeline_study_receiving import _cold_receive;"
                "_cold_receive(sys.argv[2],sys.argv[3])")
            event("cold_reopening_copied_application", application=str(copied))
            with (output / "cold.stdout.txt").open("a", encoding="utf-8") as stdout, (
                    output / "cold.stderr.txt").open("a", encoding="utf-8") as stderr:
                child = subprocess.Popen(
                    [sys.executable, "-I", "-c", bootstrap, str(copied), str(spec_path), str(cold_path)],
                    cwd=copied, stdout=stdout, stderr=stderr)
                try:
                    code = child.wait()
                except BaseException:
                    if child.poll() is None:
                        child.terminate()
                        try:
                            child.wait(timeout=10)
                        except subprocess.TimeoutExpired:
                            child.kill(); child.wait()
                    raise
                finally:
                    child = None
            if code != 0:
                raise RuntimeError("Copied-application receiving returned " + str(code) + "; retain cold.stderr.txt")
            cold = read_json(_regular(cold_path))
            if cold.get("state") != "complete" or cold.get("study_id") != transfer["id"]:
                raise ValueError("Copied application did not finish the selected original Study")
            _same(_snapshot(workspace, ledger_id), original, "Producer ledger changed during report/Study receiving")
            _same(_pin(archive), archive_identity, "Original selected archive changed during receiving")
            state.update(
                state="complete", completed_at=now(), ledger_id=ledger_id,
                scientific_report_edition_id=report_id, study_id=transfer["id"],
                years=original["years"], archive={"path": str(archive), **archive_identity},
                receiving=restored, cold_receiving=cold,
                original_ledger_unchanged=True, numerical_run_started=False, browser_started=False,
                visual_inspection="Pending actual original operator/report and every outgoing attachment inspection by producing peer.")
            event("complete", ledger_id=ledger_id, study_id=transfer["id"], years=original["years"])
            return state
        except BaseException as error:
            state.update(state="interrupted" if isinstance(error, (KeyboardInterrupt, InterruptedError)) else "failed",
                         error={"type": type(error).__name__, "message": str(error)},
                         failed_at=now())
            (output / "error.txt").write_text(traceback.format_exc(), encoding="utf-8")
            if original is not None:
                try:
                    state["original_ledger_unchanged"] = _snapshot(workspace, ledger_id) == original
                except BaseException as preservation_error:
                    state["preservation_error"] = str(preservation_error)
            event(state["state"], error=state["error"])
            raise


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", required=True, help="Original retained Workspace")
    parser.add_argument("--ledger", required=True, help="Existing completed observed timeline ledger ID")
    parser.add_argument("--out", required=True, help="New private output outside original app and Workspace")
    parser.add_argument("--title", help="Optional original scientific-report title")
    parser.add_argument("--resume", action="store_true", help="Continue this exact original saved request")
    args = parser.parse_args(argv)
    def interrupted(signum, unused):
        raise InterruptedError("Original receiving interrupted by signal " + str(signum))
    prior = signal.signal(signal.SIGTERM, interrupted)
    try:
        result = run_existing(args.workspace, args.ledger, args.out, title=args.title, resume=args.resume)
        print(json.dumps({"state": result["state"], "output": result["output"],
                          "study_id": result["study_id"], "archive": result["archive"]}), flush=True)
        return 0
    finally:
        signal.signal(signal.SIGTERM, prior)


if __name__ == "__main__":
    raise SystemExit(main())
